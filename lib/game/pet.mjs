function 非负(v) { return Math.max(0, Math.floor(Number(v) || 0)); }


// 数量表兜底：只留正整数（食物库存用）
function 规范库存(源) {
  const out = {};
  const o = 源 && typeof 源 === "object" ? 源 : {};
  for (const k of Object.keys(o)) {
    const 名 = S(k);
    const v = Math.floor(Number(o[k]) || 0);
    if (名 && 食物找(名) && v > 0) out[名] = (out[名] || 0) + v;
  }
  return out;
}


// 小屋兜底：没建过 / 老档缺字段都补默认（自动喂默认开，但只有建了屋并且有食物才会真的喂）
export function 规范小屋(源) {
  const o = 源 && typeof 源 === "object" ? 源 : {};
  return {
    已建: !!o.已建,
    库存: 规范库存(o.库存),
    自动喂: o.自动喂 === undefined ? true : !!o.自动喂,
    上次自动喂: 非负(o.上次自动喂)
  };
}


// 面板「最近动态」兜底：老档没有日志 / 脏数据都收敛成 [{毫秒,时间,文本}]，最多 后台日志上限 条
export function 规范日志(源) {
  const list = Array.isArray(源) ? 源 : [];
  const out = [];
  for (const x of list) {
    const o = x && typeof x === "object" ? x : {};
    const 文本 = S(o.文本);
    if (!文本) continue;
    const 毫秒 = 非负(o.毫秒);
    out.push({ 毫秒: 毫秒, 时间: S(o.时间) || fmt(毫秒 || Date.now()), 文本: 文本 });
    if (out.length >= 后台日志上限) break;
  }
  return out;
}


// 一只宠物的兜底：等级夹 1~等级上限(100)、体力夹 0~上限（上限随等级变，封顶 1100）、时间戳归零化、摸鱼次数补 0
export function 规范一只(源) {
  const o = 源 && typeof 源 === "object" ? 源 : {};
  const 级 = Math.max(1, Math.min(等级上限, Math.floor(Number(o.等级) || 1)));
  const 上 = 体力上限算(级);
  const 体 = o.体力 === undefined || o.体力 === null ? 上 : Math.max(0, Math.min(上, Math.floor(Number(o.体力) || 0)));
  const 收 = o.上次收益 && typeof o.上次收益 === "object" ? o.上次收益 : null;
  return {
    等级: 级,
    经验: 非负(o.经验),
    体力: 体,
    体力时间: 非负(o.体力时间),
    上次干活: 非负(o.上次干活),
    干活轮数: 非负(o.干活轮数),
    上次收益: 收 ? 汇总收益(收) : null,
    停工: S(o.停工),
    效率加成: Math.max(0, Math.min(0.5, Number(o.效率加成) || 0)),
    加成到期: 非负(o.加成到期),
    摸鱼次数: 非负(o.摸鱼次数)
  };
}


export function 读宠物(ctx, u) {
  const raw = dget(ctx, P宠物, u, null);
  const o = raw && typeof raw === "object" ? raw : {};
  const 档 = 空宠物档();
  const 宠源 = o.宠 && typeof o.宠 === "object" ? o.宠 : {};
  for (const k of Object.keys(宠源)) {
    const 名 = S(k);
    if (!宠物找(名)) continue;            // 表里没有的宠物（改名 / 脏数据）直接丢弃
    档.宠[名] = 规范一只(宠源[k]);
  }
  const 出 = S(o.出战);
  档.出战 = 出 && 档.宠[出] ? 出 : "";
  const 统 = o.统计 && typeof o.统计 === "object" ? o.统计 : {};
  档.统计 = {
    总轮数: 非负(统.总轮数), 总收获: 非负(统.总收获),
    总种植: 非负(统.总种植), 总摸鱼: 非负(统.总摸鱼)
  };
  档.小屋 = 规范小屋(o.小屋);
  // 3.1.14：金库 / 播种偏好兜底（老档缺字段自动补）
  const 库 = o.金库 && typeof o.金库 === "object" ? o.金库 : {};
  // 3.1.22 修复：这里原来漏读「启用」，导致金库开关 on 写入后下次读档又变回关闭
  //   （启用金库 → 提示成功 → 再查仍是关闭、允许购买打不开）。缺省按启用 true。
  档.金库 = { 存款: 非负(库.存款), 允许购买: !!库.允许购买, 启用: 库.启用 === undefined ? true : !!库.启用 };
  const 播 = o.播种偏好 && typeof o.播种偏好 === "object" ? o.播种偏好 : {};
  const 模 = ["种子", "菜", "药"].indexOf(S(播.模式)) >= 0 ? S(播.模式) : "";
  档.播种偏好 = { 模式: 模, 目标: 模 ? S(播.目标) : "" };
  const 轮 = o.播种轮换 && typeof o.播种轮换 === "object" ? o.播种轮换 : {};
  档.播种轮换 = { 农场: Math.max(0, Math.floor(Number(轮.农场) || 0)), 药园: Math.max(0, Math.floor(Number(轮.药园) || 0)) };
  档.日志 = 规范日志(o.日志);
  return 档;
}


