/* 供面板/测试用：给一只宠物加体力（喂食、管理员补状态都走这里） */
export function 加体力(ctx, u, 名, 量) {
  const 档 = 读宠物(ctx, u);
  const 词 = 宠物找(名);
  if (!词 || !档.宠[词.名]) return null;
  const p = 档.宠[词.名];
  p.体力 = Math.max(0, Math.min(体力上限算(p.等级), p.体力 + Math.floor(Number(量) || 0)));
  p.体力时间 = Date.now();
  写宠物(ctx, u, 档);
  return p.体力;
}


