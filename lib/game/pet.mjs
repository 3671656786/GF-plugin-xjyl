/* ============================================================
 * 五、体力：休息按时间恢复（固定速率，后台时钟不改变恢复规则）
 * ============================================================ */
/* 恢复规则：
 * · **出战中**的宠物不回体力（体力时间跟随 now，方便下次休息从此刻起算）；
 * · 其它宠物（休息中）按 floor((now − 体力时间) / 60 秒) × 休息恢复每分 回体力，封顶体力上限；
 * · 余数留在 体力时间 里（体力时间 += 分钟 × 60000），所以「差 30 秒」不会每次看面板都清零。
 */
function 恢复体力(档, now) {
  for (const 名 of Object.keys(档.宠)) {
    const p = 档.宠[名];
    const 上 = 体力上限算(p.等级);
    if (名 === 档.出战) { p.体力时间 = now; continue; }
    const 基 = Number(p.体力时间) || 0;
    if (!基) { p.体力时间 = now; continue; }
    const 分 = Math.floor((now - 基) / 60000);
    if (分 <= 0) continue;
    p.体力 = Math.min(上, p.体力 + 分 * 休息恢复每分);
    p.体力时间 = 基 + 分 * 60000;
  }
}


