// lib/game/pet.mjs —— 需求 21：宠物领养 + 农田/药园自动干活（**后台时钟 + 惰性补算，共用同一个结算**）
/* ============================================================
 * 一、这个模块干什么
 * ------------------------------------------------------------
 * · 领养宠物（**四货币**：星羽 + 金币 + 花 + 星石，按稀有度递增）→ 出战 → 它按「干活间隔」自动干活：
 *     农田：收成熟作物，没有可收的就去播背包里的种子；
 *     药园：收成熟灵田，没有可收的就按种子仓播灵种（用 herb.mjs 导出的 收田，不复制收菜逻辑）。
 * · 宠物有等级（1~10）与体力池（0~体力上限）：干活每轮扣体力，体力不足自动停工；
 *   休息（不在出战）时按**固定速率**每分钟恢复，喂食可立刻回体力（星羽 / 背包作物）。
 * · **摸鱼**：每轮干活先掷骰子，命中就本次不干活、回窝休息、回 8~15 点体力（低效宠物更容易摸鱼）；
 *   3.1.3：摸鱼只跳过这一轮，宠物继续留在出战中循环干活，不会因为摸鱼而罢工。
 *
 * 二、时间口径（本轮改造 ②：实时模拟 + 补算，两者共用同一个结算）
 * ------------------------------------------------------------
 * 旧版只有一个「惰性结算」入口（发指令 / 开面板时才补算），玩家看不到宠物真的在干活。
 * 现在两条入口同时存在，但**共用同一个 结算()**，靠存档里的 `上次干活` 推进来保证不双算：
 *   ① **后台时钟**：plugin_init 起 启动宠物时钟(ctx)，每 后台滴答毫秒(500ms) 一拍，
 *      扫 宠物.json 里「有出战宠物」的玩家，到点就替他们干 1 轮（收菜/种菜/收药田/播种），并写日志；
 *      单拍最多替 每拍最多玩家(2) 位玩家干活，单次只干到「单轮最多块(1~2)块地」（由 干一轮 保证）。
 *   ② **惰性补算**：玩家发宠物指令 / 打开面板时调 结算()，按 `现在 − 上次干活` 补算，**一次最多补 3 轮**。
 * 为什么不会重复干活：结算() 每次都从存档读 `上次干活`，干完把 `上次干活` 往后推；
 *   时钟和面板是同一个进程里的同步函数，谁先把 `上次干活` 推过去，另一方就算出 0 轮，不会重复收菜。
 * 时钟句柄是**模块级 let**，启动前先 clearInterval 旧时钟（重载时不会叠加两个时钟），
 *   并且 unref（不阻止进程退出）。plugin_cleanup 调 停止宠物时钟() 收掉。
 *
 * 三、存档
 * ------------------------------------------------------------
 * 游戏数据/宠物/宠物.json（键 = openid，带 版本 字段；读档统一走 读宠物 做兜底）：
 *   { 版本, 出战,
 *     宠: { 宠物名: { 等级, 经验, 体力, 体力时间, 上次干活, 干活轮数, 上次收益, 停工,
 *                     效率加成, 加成到期, 摸鱼次数 } },
 *     统计: { 总轮数, 总收获, 总种植, 总摸鱼 },
 *     小屋: { 已建, 库存, 自动喂, 上次自动喂 },
 *     日志: [ { 毫秒, 时间, 文本 } ] }   ← 面板「最近动态」，只留最近 后台日志上限(8) 条
 * 数值表与公式在 lib/content/pet-data.mjs，测试 .workbuddy/test/dbg-pet.mjs 逐条断言。
 * ============================================================ */
