// 玩家四种货币的余额（领养校验与提示用；名字与 领养货币 一一对应）
function 钱袋(ctx, u) {
  return {
    星羽: dn(ctx, P.星羽, u, 0),
    金币: dn(ctx, P.金币, u, 0),
    花: hasItem(ctx, u, "花"),
    星石: hasItem(ctx, u, "星石")
  };
}


// 「缺什么、缺多少」逐项列（每项都带单位，和 领养价文案 一个口径）
function 差价行(价, 有) {
  const out = [];
  for (const k of 领养货币) {
    const 需 = Math.max(0, Math.floor(Number(价[k]) || 0));
    if (需 <= 0) continue;
    const 现 = Math.max(0, Math.floor(Number(有[k]) || 0));
    out.push("· **" + k + "** 需 **" + kfmt(需) + " " + 领养货币单位[k] + "**，你有 " + kfmt(现) + " " + 领养货币单位[k]
      + (现 >= 需 ? " ✅" : " ❌ 还差 " + kfmt(需 - 现) + " " + 领养货币单位[k]));
  }
  return out;
}


// 四货币一起扣（校验已在调用方做过，这里只做扣款；每项都为 0 时直接跳过）
function 扣领养费(ctx, u, 价) {
  for (const k of 领养货币) {
    const 需 = Math.max(0, Math.floor(Number(价[k]) || 0));
    if (需 <= 0) continue;
    if (k === "星羽") addCoin(ctx, u, -需);
    else if (k === "金币") dset(ctx, P.金币, u, Math.max(0, Math.floor(Number(dn(ctx, P.金币, u, 0)) || 0) - 需));
    else takeItem(ctx, u, k, 需);          // 花 / 星石 都是背包道具，名字就叫「花」「星石」
  }
}


