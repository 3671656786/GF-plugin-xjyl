  const 段 = [];
  if (收.农田收 > 0) {
    const 物 = Object.keys(收.农田得 || {}).map((k) => k + "×" + 收.农田得[k] + " 份");
    段.push("农田收获 " + 收.农田收 + " 块地" + (物.length ? " → " + 物.join("、") : ""));
  }
  if (收.药园收 > 0) {
    const 药 = Object.keys(收.药园得 || {}).map((k) => k + "×" + 收.药园得[k] + " 份");
    段.push("药园收获 " + 收.药园收 + " 块田" + (药.length ? " → " + 药.join("、") : ""));
  }
  if (收.农田种 > 0) 段.push("农田播种 " + 收.农田种 + " 块地（" + (收.农田种名 || "种子") + "）");
