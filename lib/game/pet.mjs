export async function 宠物自动喂(ctx, t, u, 开关) {
  结算(ctx, u);
  const 档 = 读宠物(ctx, u);
  if (!档.小屋.已建) {
    await reply(ctx, t, [
      "**还没建小屋**",
      灰块(["没有自动喂食功能", "发 `星甲宠物小屋` 看造价"])
    ].join("\n"), {
      标题: "🍚 自动喂食", 行组: [row(btn("pg1", "宠物小屋", "宠物小屋"))]
    });
    return;
  }
  const s = S(开关);
  let 开 = 档.小屋.自动喂;
  if (/^(on|开|开启|1|true)$/i.test(s)) 开 = true;
  else if (/^(off|关|关闭|0|false)$/i.test(s)) 开 = false;
  else 开 = !开;                      // 不带参数 = 切换
  const 库 = 食物表.filter((x) => (档.小屋.库存[x.名] || 0) > 0);
  if (开 && !库.length) {
    await reply(ctx, t, [
      "**小屋库存是空的**",
      灰块(["先 `星甲宠物买食 <食物名> <数量>` 补货，再开启自动喂食"])
    ].join("\n"), {
      标题: "🍚 自动喂食", 行组: [row(btn("pg2", "宠物小屋", "宠物小屋"), btn("pg3", "买食", "宠物小屋"))]
    });
    return;
  }
  档.小屋.自动喂 = 开;
  写宠物(ctx, u, 档);
  const 喂行 = 开
    ? ["出战的宠物体力低于 " + 自动喂食阈值 + " 点时，从库存自动吃 1 份（每 " + 自动喂食间隔秒 + " 秒最多 1 份）"]
    : ["关闭后宠物饿了只会停止干活，需要手动 `星甲宠物喂食`"];
  喂行.push("库存：" + (库.length ? 库.map((x) => x.名 + "×" + 档.小屋.库存[x.名] + " 份").join(" · ") : "空"));
  await reply(ctx, t, [
    "**自动喂食已 " + (开 ? "开启" : "关闭") + "**",
    灰块(喂行)
  ].join("\n"), {
    标题: "🍚 自动喂食",
    行组: [row(actBtn("pg4", 开 ? "⚡关闭" : "⚡开启", "petautofeed|" + (开 ? "off" : "on")), btn("pg5", "宠物小屋", "宠物小屋"), btn("pg6", "宠物面板", "宠物"))]
  });
}


