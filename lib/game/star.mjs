/* 3.3.26：固定小时阶梯表 —— 按「第几天」分档，档内每小时利率固定。
 * 边界（第几小时）：1–24 / 25–72 / 73–168 / 169–264 / 265–336 / >336。 */
const 贷款固定阶梯 = [
  { 止: 24,  率: 0.00025  },  // 第 1 天：0.025%/小时
  { 止: 72,  率: 0.0005   },  // 第 2–3 天：0.05%/小时
  { 止: 168, 率: 0.00075  },  // 第 4–7 天：0.075%/小时
  { 止: 264, 率: 0.001    },  // 第 8–11 天：0.1%/小时
  { 止: 336, 率: 0.0015   },  // 第 12–14 天：0.15%/小时
];

// 兼容旧展示：第 N 天对应的小时利率（取该天所属档位）。
export function 贷款阶梯利率(第几天) {
  const N = Math.max(1, Math.floor(Number(第几天) || 1));
  if (N > 贷款阶梯天数) return 贷款超期利率;
  return 贷款小时利率档((N - 1) * 24 + 1);
}

/* 3.3.26：按「第几个计息小时」返回该小时利率 —— 固定小时阶梯（档内恒定）。
 * 第1–24h 0.025% · 25–72h 0.05% · 73–168h 0.075% · 169–264h 0.1% · 265–336h 0.15%。
 * 第 337 小时起（超 14 天）：非分期 0.125%/小时、分期 0.0825%/小时。 */
export function 贷款小时利率档(第几小时, 分期 = false) {
  const h = Math.max(1, Math.floor(Number(第几小时) || 1));
  if (h > 贷款阶梯小时) return 分期 ? 贷款分期超期利率 : 贷款超期利率;
  for (const d of 贷款固定阶梯) if (h <= d.止) return d.率;
  return 贷款固定阶梯[贷款固定阶梯.length - 1].率;
}

/* 3.3.18：借款时长 → 应计息小时数。
 * ≤30 分钟 → 0；否则向上取整到整小时（不足 1 小时按 1 小时）。 */
export function 借款计息小时(时长毫秒) {
  const ms = Math.max(0, Number(时长毫秒) || 0);
  if (ms === 0 || ms <= 首小时门槛毫秒) return 0;
  return Math.ceil(ms / 3600000);
}

