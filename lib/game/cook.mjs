export const 加点表 = { 攻击: { 路径: () => P.攻击, 每点: 30 }, 防御: { 路径: () => P.防御, 每点: 25 }, 血量: { 路径: () => P.血量上限, 每点: 60 }, 闪避: { 路径: () => P.闪避, 每点: 0.5 }, 暴击率: { 路径: () => P.暴击率, 每点: 0.5 }, 暴击伤害: { 路径: () => P.暴伤, 每点: 5 } };


export function 加点记录(ctx) { const v = dget(ctx, P.装备加点, "记录", {}); return v && typeof v === "object" ? v : {}; }


export function 存加点记录(ctx, o) { dset(ctx, P.装备加点, "记录", o); }


export function 已用点(ctx, u, 名) {
  const all = 加点记录(ctx);
  const mine2 = all[u] && typeof all[u] === "object" ? all[u] : {};
  const it = mine2[S(名)];
  return it && typeof it === "object" ? Math.max(0, Math.floor(n(it.用, 0))) : 0;
}


export async function 加点(ctx, t, u, name, 属性名, 点数) {
  const e = 装备定义(name);
  if (!e) { await reply(ctx, t, "只有武器 / 护甲可以加点。", { 标题: "➕ 加点失败", 按钮: [btn("ad1", "背包", "背包")] }); return; }
  const f = S(属性名);
  const cfg = 加点表[f];
  if (!cfg) { await reply(ctx, t, "可加属性：" + Object.keys(加点表).join(" · ") + "\n用法：`星甲加点#" + e.名 + "#攻击#1`", { 标题: "➕ 加点失败" }); return; }
  const 总点 = 升级总点(ctx, u, e.名);
  const 用 = 已用点(ctx, u, e.名);
  const 可用 = Math.max(0, 总点 - 用);
  if (可用 < 1) {
    await reply(ctx, t, [
      "【" + e.名 + "】没有可用升级点。",
      "",
      "升级点：总 " + 总点 + " · 已用 " + 用 + " · 可用 0",
      "用 `星甲升级装备#" + e.名 + "#1` 升级即可获得升级点。"
    ].join("\n"), { 标题: "➕ 加点失败", 行组: [row(actBtn("ad2", "⚡升1级", "upeq|" + e.名 + "|1"), btn("ad3", "背包", "背包"))] });
    return;
  }
  const k = Math.min(Math.max(1, Math.floor(Number(点数) || 1)), 可用);
  const 增 = cfg.每点 * k;
  dset(ctx, cfg.路径(), u, Math.max(0, dn(ctx, cfg.路径(), u, 0) + 增));
  const all = 加点记录(ctx);
  const mine2 = all[u] && typeof all[u] === "object" ? all[u] : {};
  const it = mine2[e.名] && typeof mine2[e.名] === "object" ? mine2[e.名] : {};
  it.用 = n(it.用, 0) + k;
  it[f] = n(it[f], 0) + k;
  mine2[e.名] = it;
  all[u] = mine2;
  存加点记录(ctx, all);
  recPwr(ctx, u);
  // 2.5.44：加「闪避 / 暴击率」可能顶到上限，超出部分按 0.01% : 1 折算成经验
  const 溢出 = (f === "闪避" || f === "暴击率") ? 溢出转经验(ctx, u) : null;
  await reply(ctx, t, [
    "## ➕ 加点成功",
    "",
    "【" + e.名 + "】" + f + " +" + fmtNum(增) + "（用了 " + k + " 点）",
    "升级点 总 " + 总点 + " · 已用 " + (用 + k) + " · 剩余可用 " + Math.max(0, 总点 - 用 - k),
    (溢出 && 溢出.经验 ? "\n" + 溢出文案(溢出) : "")
  ].filter((x) => x !== null && x !== undefined && x !== false).join("\n"), {
    标题: "➕ 加点",
    行组: [
      row(actBtn("ad4", "⚡再加1点", "addpt|" + e.名 + "|" + f + "|1"), actBtn("ad5", "⚡属性", "info"), actBtn("ad6", "⚡背包", "bag|1"))
    ]
  });
}
