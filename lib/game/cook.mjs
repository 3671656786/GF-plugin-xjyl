// 2.5.1：厨房每日上限 —— 每天最多提供 6000 血量 / 500 攻击力 / 250 防御，超出部分只加经验
// 2.9.0（需求 4）：补上暴伤每日上限 50（此前暴伤无上限，高级菜可无限堆暴伤）
export const 菜日上限 = { 血量: 6000, 攻击: 500, 防御: 250, 暴伤: 50 };


export function 菜每日档(ctx) { return "游戏数据/修炼/菜品每日.json"; }


export function 读菜每日(ctx, u) {
  const 档 = 菜每日档(ctx);
  const 今 = ymd();
  let v = dget(ctx, 档, u, null);
  if (!v || typeof v !== "object" || v.日期 !== 今) v = { 日期: 今, 血量: 0, 攻击: 0, 防御: 0, 暴伤: 0 };
  if (v.暴伤 === undefined) v.暴伤 = 0;
  return v;
}


export function 写菜每日(ctx, u, v) { dset(ctx, 菜每日档(ctx), u, v); }


// 食用菜品：血量恢复 + 永久属性 + 经验（带每日上限）
export async function 吃菜(ctx, t, u, name, k) {
  const r = 菜谱(name);
  if (!r) return false;
  const 份 = Math.min(Math.max(1, Math.floor(Number(k) || 1)), hasItem(ctx, u, name));
  if (份 < 1) { await reply(ctx, t, "你没有【" + name + "】。\n先去 `星甲做菜` 做一份。", { 标题: "🍽️ 食用失败", 按钮: [btn("ck18", "星甲食堂", "做菜")] }); return true; }
  takeItem(ctx, u, name, 份);
  const p = attrs(ctx, u);
  const 日 = 读菜每日(ctx, u);
  const 吃 = [];
  const 超限 = [];
  // 血量（含血量上限）合并计入 6000 上限
  const 回血量 = (Number(r.血量) || 0) + (Number(r.血量上限) || 0);
  if (回血量 > 0) {
    const 剩 = Math.max(0, 菜日上限.血量 - 日.血量);
    const 可加 = Math.min(回血量 * 份, 剩);
    if (可加 > 0) {
      if (r.血量) { const 新 = Math.min(p.血量上限, p.血量 + 可加); dset(ctx, P.血量, u, 新); 吃.push("血量 +" + (新 - p.血量)); }
      if (r.血量上限) { dset(ctx, P.血量上限, u, p.血量上限 + 可加); dset(ctx, P.血量, u, Math.min(dn(ctx, P.血量上限, u, 500), dn(ctx, P.血量, u, 0) + 可加)); 吃.push("血量上限 +" + 可加); }
      日.血量 += 可加;
    }
    if (可加 < 回血量 * 份) 超限.push("血量已达到今日上限（" + 菜日上限.血量 + "）");
  }
  // 攻击力
  if (r.攻击) {
    const 剩 = Math.max(0, 菜日上限.攻击 - 日.攻击);
    const 可加 = Math.min(r.攻击 * 份, 剩);
    if (可加 > 0) { dset(ctx, P.攻击, u, p.攻击 + 可加); 吃.push("攻击力 +" + 可加 + "（永久）"); 日.攻击 += 可加; }
    if (可加 < r.攻击 * 份) 超限.push("攻击力已达到今日上限（" + 菜日上限.攻击 + "）");
  }
  // 防御
  if (r.防御) {
    const 剩 = Math.max(0, 菜日上限.防御 - 日.防御);
    const 可加 = Math.min(r.防御 * 份, 剩);
    if (可加 > 0) { dset(ctx, P.防御, u, p.防御 + 可加); 吃.push("防御 +" + 可加 + "（永久）"); 日.防御 += 可加; }
    if (可加 < r.防御 * 份) 超限.push("防御已达到今日上限（" + 菜日上限.防御 + "）");
  }
  // 3.0.0（需求 23）：厨房等非副本玩法只给 血量 / 攻击力 / 防御力，
  //   不再提供 暴击率 / 暴击伤害 这类会持续放大伤害的属性（原来暴击率还没有每日上限，正是"一天伤害涨太多"的来源）
  if ((r.暴击率 || r.暴伤) && !吃.length && !超限.length) 超限.push("本菜只提供 血量 / 攻击力 / 防御力（暴击类属性已按需求下线）");
  写菜每日(ctx, u, 日);
  // 2.5.52：做菜经验也随等级成长（每份按「菜品经验」为基础折算）
  const 菜经验 = 日常经验((r.经 || 0) * 份, p.等级, "做菜");
  const up = 加经验(ctx, u, 菜经验);
  吃.push("经验 +" + 菜经验 + (up.升级 ? "（升级 → Lv." + up.等级 + "）" : ""));
  recPwr(ctx, u);
  // 2.5.44：暴击率超出上限的部分按 0.01% : 1 折算成经验
  const 溢出 = 溢出转经验(ctx, u);
  tInc(ctx, u, "使用道具");
  const 余 = "今日剩余额度：血量 " + Math.max(0, 菜日上限.血量 - 日.血量) + " · 攻击力 " + Math.max(0, 菜日上限.攻击 - 日.攻击) + " · 防御 " + Math.max(0, 菜日上限.防御 - 日.防御) + " · 暴伤 " + Math.max(0, 菜日上限.暴伤 - 日.暴伤);
  await reply(ctx, t, ["吃了 " + 份 + " 份【" + name + "】", ""].concat(
    吃.map((x) => "· " + x),
    (超限.length ? ["", "⚠️ " + 超限.join("；") + "（超出部分只加经验）"] : []),
    (溢出.经验 ? ["", 溢出文案(溢出)] : []),
    ["", 余]
  ).join("\n"), {
    标题: "🍽️ " + name,
    行组: [row(actBtn("ck19", "⚡再吃一份", "useitem|" + name + "|1"), actBtn("ck20", "⚡做一份", "cook|" + name + "|1"), actBtn("ck21", "⚡属性", "info"), actBtn("ck22", "⚡食堂", "cookpanel"))]
  });
  return true;
}



