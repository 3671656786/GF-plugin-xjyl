export function 技能效果文案(技) {
  const s = 技 || {};
  const t = [];
  if (Number(s.段) > 1) t.push(s.段 + "段");
  if (Number(s.破防) > 0) t.push("破防" + s.破防 + "%");
  if (Number(s.暴击) > 0) t.push("暴击+" + s.暴击 + "%");
  if (Number(s.回血) > 0) t.push("回血" + s.回血 + "%");
  if (Number(s.减伤) > 0) t.push("减伤" + s.减伤 + "%");
  return t.length ? t.join("·") : "单体高伤";
}


