/* ---------- 2.4.1 灰色字体：用 Markdown 引用块（> 前缀）呈现新版 UI 的灰底灰字 ---------- */
export function 灰块(lines) {
  return (Array.isArray(lines) ? lines : [lines])
    .map((x) => {
      const t = String(x === undefined || x === null ? "" : x);
      return t === "" ? ">" : "> " + t;
    })
    .join("\n");
}


// 灰块 + 分页脚注
export function 灰面板(标题, lines) { return "## " + 标题 + "\n" + 灰块(lines); }


// 2.4.2 黑灰共存：标题/物品名用黑色加粗，其余行用灰色引用块
//   parts = [[文本, 是否灰], ...]
export function 灰混(parts) {
  return (Array.isArray(parts) ? parts : []).map((x) => {
    const t = String((x && x[0]) === undefined || (x && x[0]) === null ? "" : x[0]);
    const 是灰 = !(x && x[1] === false);
    if (!是灰) return "**" + t + "**";
    return t === "" ? ">" : "> " + t;
  }).join("\n");
}



