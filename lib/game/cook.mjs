export function 职业定义(名) {
  const s = S(名);
  return s ? (职业表.filter((x) => x.名 === s)[0] || null) : null;
}


// 某职业的技能表（拷一份并补上序号 1..N，序号 = 自动出招 `序号:N` 里的序号）
export function 职业技能表(职业名) {
  const j = 职业定义(职业名);
  if (!j) return [];
  return j.技能.map((s, i) => Object.assign({}, s, { 序: i + 1, 职业: j.名 }));
}


