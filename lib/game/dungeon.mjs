export function 写BOSS保底(ctx, u, id, o) {
  const all = BOSS保底表(ctx);
  const 取 = (k) => Math.max(0, Math.floor(n(o && o[k], 0)));
  all[u + "_" + S(id)] = { 普通: 取("普通"), 史诗: 取("史诗"), 传说: 取("传说") };
  dset(ctx, P.BOSS保底, "记录", all);
}


export function 剩普通保底(ctx, u, id) { return Math.max(0, 保底普通次数 - 读BOSS保底(ctx, u, id).普通); }


export function 剩史诗保底(ctx, u, id) { return Math.max(0, 保底史诗次数 - 读BOSS保底(ctx, u, id).史诗); }


export function 剩传说保底(ctx, u, id) { return Math.max(0, 保底传说次数 - 读BOSS保底(ctx, u, id).传说); }


// 品质名归一（内部小工具，对外也能用）
export function 品名(品质) { const s = S(品质).trim(); return s === "史诗" || s === "传说" ? s : "普通"; }


// 通用版：剩保底(ctx, u, id, 品质)
export function 剩保底(ctx, u, id, 品质) {
  const 品 = 品名(品质);
  return Math.max(0, 保底次数表[品] - 读BOSS保底(ctx, u, id)[品]);
}


export function 五倍属性(o) {
  const r = {};
  for (const k in o) {
    if (!Object.prototype.hasOwnProperty.call(o, k)) continue;
    // 2.8.0：词条是嵌套对象，不能当数字乘（否则整条变 NaN）
    if (k === "词条" && o[k] && typeof o[k] === "object") {
      const w = {};
      for (const kk of Object.keys(o[k])) w[kk] = Math.round((Number(o[k][kk]) || 0) * 5 * 100) / 100;
      r[k] = w;
      continue;
    }
    r[k] = Math.round((Number(o[k]) || 0) * 5 * 100) / 100;
  }
  return r;
}


// BOSS 掉落（3.0.0）：三档品质各自独立判定 —— 普通 10% / 史诗 5% / 传说 1%，
//   各自独立保底（10 / 25 / 100 次），三档可能同时出；每档再按 50% 决定 武器 / 护甲。
//   返回 [{ 名, 品质, 类, 保底 }]，品质 ∈ 普通 / 史诗 / 传说。
export function BOSS掉落(ctx, u, d) {
  const c = 读BOSS保底(ctx, u, d.id);
  const 出 = [];
  const 落倍 = 称号倍(ctx, u, "掉落");
  for (const 品 of ["传说", "史诗", "普通"]) {
    const 保底次数 = 保底次数表[品];
    const 爆率 = BOSS爆率表[品];
    const 必出 = c[品] + 1 >= 保底次数;
    if (!必出 && Math.random() >= Math.min(0.5, 爆率 * 落倍)) { c[品] += 1; continue; }
    const 类 = Math.random() < 0.5 ? "武器" : "护甲";
    const nm = 装备名(d, 类, 品);
    入背包(ctx, u, nm, 1);
    出.push({ 名: nm, 品质: 品, 类: 类, 保底: 必出 });
    c[品] = 0;
  }
  写BOSS保底(ctx, u, d.id, c);
  return 出;
}


// 普通副本掉落（3.0.0 需求 4.9 收口）：三档品质**各自独立判定 + 各自保底计数**（10 / 25 / 100 次），
//   数值与 BOSS 完全一样（副本爆率表 / 副本保底次数表，就是 BOSS 那两张表的别名）。
//   与 BOSS 的区别只在「一次最多出一件」：按 传说 → 史诗 → 普通 从高到低依次判定，命中即止；
//   没轮到的低品质本次**不累加计数**（避免高品出货把低品保底白白推进）。
//   这样既满足「三档独立爆率 + 独立保底」，又保持 `副本掉落()` 的旧返回契约（combat.mjs 单件渲染）。
//   返回 { 名, 品质, 类, 保底 } 或 null。
export function 副本掉落(ctx, u, d) {
  const c = 读BOSS保底(ctx, u, d.id);   // 与 BOSS 共用存档（键 = 用户_副本id，不会撞）
  const 落倍 = 称号倍(ctx, u, "掉落");
  let 出 = null;
  for (const 品 of ["传说", "史诗", "普通"]) {
    const 保底次数 = 副本保底次数表[品];
    const 爆率 = 副本爆率表[品];
    const 必出 = c[品] + 1 >= 保底次数;
    if (!必出 && Math.random() >= Math.min(0.5, 爆率 * 落倍)) { c[品] += 1; continue; }
    const 类 = Math.random() < 0.5 ? "武器" : "护甲";
    const nm = 装备名(d, 类, 品);
    入背包(ctx, u, nm, 1);
    出 = { 名: nm, 品质: 品, 类: 类, 保底: 必出 };
    c[品] = 0;
    break;   // 一次最多一件
  }
  写BOSS保底(ctx, u, d.id, c);
  return 出;
}
