/* 3.0.0（Lead 追加）婚姻加成 hook（需求：副本/BOSS 的经验 / 星羽 / 金币 各调一次 婚姻加成()，把返回值给配偶）
 *  · 婚姻模块 lib/game/marriage.mjs 由 Lead 维护；这里**惰性加载 + 缺文件/缺导出都静默跳过**，
 *    文件到位后自动生效，不需要再回来改 combat.mjs / dungeon.mjs。
 *  · 用动态 import 避免 dungeon ↔ marriage 的静态循环依赖（marriage 大概率要读 attrs / giveItem）。
 *  · 返回配偶实际拿到的数值（0 = 没有配偶 / 模块未就绪 / 加成 0）。
 */
let _婚姻模块 = { 试过: false, 模块: null };


async function 婚姻模块取() {
  if (_婚姻模块.试过) return _婚姻模块.模块;
  _婚姻模块.试过 = true;
  try { _婚姻模块.模块 = await import("././marriage.mjs"); }
  catch (e) { _婚姻模块.模块 = null; }
  return _婚姻模块.模块;
}


export async function 婚姻分成(ctx, u, 项, 数值) {
  const m = await 婚姻模块取();
  if (!m || typeof m.婚姻加成 !== "function" || typeof m.配偶 !== "function") return 0;
  try {
    const 伴 = S(await m.配偶(ctx, u));
    if (!伴 || 伴 === S(u)) return 0;
    const 加 = Math.max(0, Math.floor(Number(await m.婚姻加成(ctx, u, 项, 数值)) || 0));
    if (加 <= 0) return 0;
    if (项 === "经验") 加经验(ctx, 伴, 加);
    else if (项 === "金币") dset(ctx, P.金币, 伴, dn(ctx, P.金币, 伴, 0) + 加);
    else addCoin(ctx, 伴, 加);
    pushLog(ctx, 伴, "婚姻分成 " + 项 + " +" + kfmt(加) + "（来自配偶副本通关）");
    return 加;
  } catch (e) {
    if (ctx && ctx.logger && ctx.logger.warn) ctx.logger.warn("[xjyl] 婚姻分成失败:", e && (e.message || e));
    return 0;
  }
}


