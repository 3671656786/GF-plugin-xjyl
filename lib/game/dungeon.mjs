// 装备名（全局唯一）：品质·名·尾缀；尾缀 锋/铠 = 副本，刃/甲 = BOSS
//   两套后缀完全不同 ⇒ 即使副本名与 BOSS 名同名（如「宿难」），三档六件也绝不会重名。
export function 装备名(d, 类, 品质) {
  const 品 = 规范品质(品质);
  const 是BOSS = !!(d && (d.BOSS === true || Number(d.id) >= 200));
  const 护甲 = S(类) === "护甲";
  const 部件 = 是BOSS ? (护甲 ? "甲" : "刃") : (护甲 ? "铠" : "锋");
  return 品 + "·" + S(d && d.名) + "·" + 部件;
}


/* 旧装备名 → 新装备名（幂等，2.x 存档兼容）
 *   专属·X刃 / 专属·X甲      → 普通·X·锋 / 普通·X·铠    （旧「副本专属」）
 *   BOSS·X·刃 / BOSS·X·甲    → 普通·X·刃 / 普通·X·甲    （旧 BOSS 普通档）
 *   传说·X·刃 / 传说·X·甲    → **原样保留**（旧版 BOSS 传说名 = 新 BOSS 传说名，一字不差，装备直接可用）
 * 已经是新名字的原样返回（迁移可反复执行，不会二次改名）。
 */
export function 规范装备名(name) {
  const nm = S(name);
  if (!nm) return "";
  let m = nm.match(/^专属[·・](.+)([刃甲])$/);
  if (m) return "普通·" + m[1] + "·" + (m[2] === "刃" ? "锋" : "铠");
  m = nm.match(/^BOSS[·・](.+)[·・]([刃甲])$/);
  if (m) return "普通·" + m[1] + "·" + m[2];
  return nm;
}


