/* 3.0.0（需求 11 修订）：BOSS 装备三档都带「真伤概率 + 闪避率」基础词条（旧版口径），
 *   传说档再叠加专属词条（吸血 / 追击 / 抗暴 / 闪击 / 反击 等）。
 *   档位倍率：普通 ×1（真伤封 12 / 闪避封 6）· 史诗 ×2（封 24 / 12）· 传说 ×5（封 60 / 40，走 传说词条）。
 *   副本装备仍然只有传说档带专属词条，普通/史诗空表。
 */
function BOSS基础词条(L, 品) {
  const 倍 = 品 === "传说" ? 5 : (品 === "史诗" ? 2 : 1);
  const 真 = Math.min(12 * 倍, (0.6 + L * 0.06) * 倍);
  const 闪 = Math.min(6 * 倍, (0.4 + L * 0.03) * 倍);
  return { 真伤概率: Math.round(真 * 100) / 100, 闪避率: Math.round(闪 * 100) / 100 };
}

export function 装备词条(L, 类, 是BOSS, 品) {
  if (!是BOSS) return 品 === "传说" ? 传说词条(L, 类, false) : {};
  // BOSS 三档都带「真伤概率 + 闪避率」；传说再叠加专属词条
  const 基 = BOSS基础词条(L, 品);
  return 品 === "传说" ? Object.assign(基, 传说词条(L, 类, true)) : 基;
}


function 传说词条上限() {
  return { 吸血: 50, 追击率: 50, 追击伤害: 45, 真伤概率: 60, 抗暴率: 35, 闪击率: 50, 反击率: 35, 反击伤害: 40, 闪避率: 40 };
}


function 裁传说词条(键, v) { const 上 = 传说词条上限()[键]; const x = Math.max(0, Number(v) || 0); return Math.round(Math.min(上, x) * 100) / 100; }


