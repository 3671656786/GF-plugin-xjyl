  for (const 类 of ["武器", "护甲"]) { const it = 槽项(槽旧, 类); if (it) 槽新[类] = { 名: it.名, 强化: it.强化 }; }
  存装备槽(ctx, u, 槽新);
  dset(ctx, P.开号, u, "已");
