/* ============================================================
 * 3.0.0（需求 A）翻倍挑战：一次挑战 = **连续打 N 次**（N = 1~5）
 *  · 敌人 **血量 × N**；
 *  · 敌人 **其他属性（攻 / 防 / 暴击率 / 暴伤 / 词条强度）固定 ×1.5**，不随 N 变（5 次也是 ×1.5）；
 *  · 冷却 × N（副本 10 分 → 5 次 50 分；BOSS 20 分 → 5 次 100 分）；
 *  · 掉落 / 保底 **按 N 次独立结算**（每件装备、星石、刷新卡、生长药水各 roll N 次，保底计数 +N）——
 *    口径写死成「真的打了 N 场」，所以不会出现「吃了 N 次保底却不掉」；
 *  · 经验 / 星羽 / 星核 / 金币兽金币 × N（首通加成只给第 1 场）；
 *  · 入场费（BOSS 金币+花）**不变**，只收 1 份；胜利返还 80% 入场也按 1 份算。
 * ============================================================ */
export const 翻倍上限 = 5;
export const 翻倍属性倍 = 1.5;


export function 翻倍次数(v) {
  const n = Math.floor(Number(v));
  if (!Number.isFinite(n) || n <= 1) return 1;
  return Math.max(1, Math.min(翻倍上限, n));
}


// 只放大「属性」：攻 / 防 / 暴击率 / 暴伤 / 词条（血量不在这里乘 —— 血量由 翻倍敌数据 单独 ×N）
export function 翻倍敌属性(d, 翻倍) {
  const n = 翻倍次数(翻倍);
  if (!d || n <= 1) return d;
  const k = 翻倍属性倍;
  const 源词 = (d.词条 && typeof d.词条 === "object") ? d.词条 : {};
  const 词 = {};
  for (const key of Object.keys(源词)) {
    词[key] = typeof 源词[key] === "number" ? Math.round(源词[key] * k * 100) / 100 : 源词[key];
  }
  // Symbol（敌方标记 / 模拟档位）不会被 Object.keys 列出，单独拷贝，别丢
  for (const s of Object.getOwnPropertySymbols(源词)) 词[s] = 源词[s];
  return Object.assign({}, d, {
    攻: Math.max(1, Math.round((Number(d.攻) || 0) * k)),
    防: Math.max(0, Math.round((Number(d.防) || 0) * k)),
    暴: (Number(d.暴) || 0) * k,
    暴伤: (Number(d.暴伤) || 0) * k,
    闪避率: (Number(d.闪避率) || 0) * k,
    词条: 词,
    翻倍: n
  });
}


// 翻倍后的完整出场数据：属性 ×1.5 + 血量 ×N
export function 翻倍敌数据(d, 挑战战力, 翻倍) {
  const 敌 = 敌数据(d, 挑战战力);
  const n = 翻倍次数(翻倍);
  const 属性 = 翻倍敌属性(敌, n);
  if (!属性) return 敌;
  return Object.assign({}, 属性, { 血: Math.max(1, Math.round((Number(敌.血) || 1) * n)), 翻倍: n });
}


