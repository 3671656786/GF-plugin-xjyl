// 「推荐战力」= 用敌人自己的攻/防/血，按玩家的战力公式镜像算一遍（战力刚好对上 → 缩放 ≈ 1.0）
export function 敌推荐战力(d) {
  const 段 = Math.max(1, Number(d && d.段) || 1);
  const 力 = Math.max(1, Number(d && d.力) || 1);
  // 2.9.2（B1 修复）：普通副本改成与副本表同源的 副本基准属性(段)（就是 敌数据()/战斗用的那份），
  //   原来是 攻=力×0.19 / 血=力×4.2 / 防=力×0.13 的旧系数兜底，跟副本表实际
  //   （血≈力×2.5~3、攻≈力×0.10~0.15、防≈力×0.07~0.10）差得很远，玩家会误判推荐战力。
  //   BOSS 条目自带 血/攻/防，直接用，缩放结果与之前完全一致（不动标定）。
  const 本 = !(d && (d.BOSS || Number(d.id) >= 200));
  const 基 = 本 ? 副本基准属性(段) : (d || {});
  const 攻 = Number(基.攻) || Number(d && d.攻) || 力 * 0.13;
  const 血 = Number(基.血) || Number(d && d.血) || 力 * 2;
  const 防 = Number(基.防) || Number(d && d.防) || 力 * 0.10;
  const base = 攻 * 3.5 + 血 + 防 * 1.2 + 10 * 20 + 100 * 2;
  return Math.max(1, base * (1 + 段 * 0.02));
}


// 按挑战者战力缩放：战力远超推荐 → 敌人上调（但最多 +20%）；战力不足 → 敌人下调（最多 −20%）
// 2.9.0（需求 1）：动态缩放只对 BOSS 生效；普通副本改为固定数值（条目写多少就打多少）
// 2.10.0（需求 4.1）：**动态缩放整体停用** —— 敌军数值只由段位 / 层数决定，不再读玩家战力。
//   下面两个导出仅为兼容 misc.mjs / 控制台 / 旧测试的引用而保留（敌数据() 已不再调用）。
export const 敌缩放幅度 = 0.2;


export function 敌缩放系数(挑战战力, 推荐战力) {
  const a = Math.max(1, Number(挑战战力) || 0);
  const b = Math.max(1, Number(推荐战力) || 1);
  const 原始 = Math.pow(a / b, 0.3);
  return Math.max(1 - 敌缩放幅度, Math.min(1 + 敌缩放幅度, 原始));
}


// 副本 / BOSS 的实际出场数据：
//   2.9.0（需求 1）副本 = 固定数值（缩放恒为 1，条目写多少打多少）；
//   2.10.0（需求 4.1）**BOSS 也改为固定数值** —— 缩放恒为 1（不再按挑战者战力 ±20%）。
//   2.10.0（需求 4.3）普通副本同样携带词条（由段位决定的固定低档词条，见 副本敌人词条）。
export function 敌数据(d, 挑战战力) {
  if (!d) return null;
  const 本 = !(d.BOSS || Number(d.id) >= 200);      // 普通副本（星甲副本）；BOSS / 金币兽走另一套
  const 基 = (本 && !(Number(d.血) > 0)) ? 副本基础属性(d) : d;
  const k = 1;   // 2.10.0：三档全部固定数值（挑战战力只用于面板展示，不参与任何缩放）
  // 2.9.7：用 Symbol 给敌方词条加内部标记；Object.keys / JSON 都看不到，旧词条契约不变。
  // t-balance4 的模拟器会复制这份词条，统一伤害层因此也能识别哪一侧是敌方。
  // 2.10.0：普通副本的词条不再为空 —— 条目没写时按段位取 副本敌人词条（固定值）。
  const 基词 = (基 && 基.词条) || (d && d.词条) || (本 ? 副本敌人词条 : {});
  const 敌词 = Object.assign({}, 基词);
  // 旧 t-balance4 只靠复制词条识别 BOSS；普通副本胜率是它的对照组，真实战斗则显式传 敌方:true，
  // 因而普通副本实战仍有三档机制，而基线对照不会被新机制污染。
  if (!本) 敌词[敌方标记] = true;
  return Object.assign({}, d, {
    本: 本, 缩放: k,
    血: Math.max(1, Math.round((Number(基.血) || 1) * k)),
    攻: Math.max(1, Math.round((Number(基.攻) || 0) * k)),
    防: Math.max(0, Math.round((Number(基.防) || 0) * k)),
    暴: Number(基.暴) || 0,
    暴伤: Number(基.暴伤) || 0,
    闪避率: Number(基.闪避率 !== undefined ? 基.闪避率 : (基.闪避 || 0)) || 0,
    词条: 敌词
  });
}


