export function 取信用分(ctx, u) {
  // 注意：0 是合法分数（失信），不能写成 `Number(v) || 默认` —— 那样 0 会被吞掉变回默认分
  const v = dget(ctx, P.信用分, u, null);
  if (v === null || v === undefined || v === "") return 信用默认;
  const n = Number(v);
  if (!Number.isFinite(n)) return 信用默认;
  return Math.max(0, Math.min(信用上限, Math.floor(n)));
}


export function 记信用事件(ctx, u, 事由, 变化) {
  const v = dget(ctx, P.信用事件, u, []);
  const list = Array.isArray(v) ? v.slice() : [];
  list.unshift({ 时间: fmt(), 事由: S(事由), 变化: Math.floor(Number(变化) || 0) });
  dset(ctx, P.信用事件, u, list.slice(0, 20));
}


/* 2.9.8（需求 5）奖励分：主分满 100 后继续积累，上限 1000；每满 50 自动发放一次奖励
 *   奖励内容（参考游戏内价值体系：打工一次 1~5 千、星核来自 BOSS）：星羽 8000 + 星核 2 + 幸运币 1
 *   发完扣 50 继续攒；面板「星甲信用分」多一行显示当前奖励分。
 */
export const 奖励分上限 = 1000;


export const 奖励分步长 = 50;


export const 奖励星羽 = 8000, 奖励星核 = 2, 奖励幸运币 = 1;


export function 取奖励分(ctx, u) {
  return Math.max(0, Math.min(奖励分上限, Math.floor(Number(dn(ctx, P.奖励分, u, 0)) || 0)));
}


export function 加奖励分(ctx, u, v, 事由) {
  let 分 = 取奖励分(ctx, u) + Math.max(0, Math.floor(Number(v) || 0));
  if (分 > 奖励分上限) 分 = 奖励分上限;
  dset(ctx, P.奖励分, u, 分);
  let 发了 = 0;
  while (取奖励分(ctx, u) >= 奖励分步长) {
    dset(ctx, P.奖励分, u, 取奖励分(ctx, u) - 奖励分步长);
    addCoin(ctx, u, 奖励星羽);
    addCore(ctx, u, 奖励星核);
    giveItem(ctx, u, "幸运币", 奖励幸运币);
    发了 += 1;
    pushLog(ctx, u, "奖励分满 " + 奖励分步长 + " 自动发奖：星羽 +" + 奖励星羽 + " · 星核 +" + 奖励星核 + " · 幸运币 +" + 奖励幸运币 + "（" + S(事由) + "）");
  }
  return { 分: 取奖励分(ctx, u), 发了: 发了 };
}


/* 2.9.10（需求 4）：每日加分上限 —— 信用分正向加分当日累计 ≤ 10，奖励分（信用溢出转化）当日累计 ≤ 25。
 *   · 超出部分不发放、不补发；扣分（贷款逾期）不受限、不计数。
 *   · 计数存「每日进度(当天)」，随现有每日重置自动清零（次日可继续加分）。
 *   · 主分已满 100 后的正向加分只走奖励分转化（受 25/日 限），不占用信用 10/日 名额。
 */
export const 信用每日上限 = 10, 奖励分每日上限 = 25;


export function 日取量(ctx, u, 键) { return Math.max(0, Math.floor(Number(tProg(ctx, u)[键]) || 0)); }


export function 日加量(ctx, u, 键, v) {
  if (!u || !键) return;
  const o = tProg(ctx, u);
  o[键] = Math.max(0, (Number(o[键]) || 0) + Math.floor(Number(v) || 0));
  dset(ctx, P.每日进度(ymd()), u, o);
}


export function 加信用分(ctx, u, v, 事由) {
  const 旧 = 取信用分(ctx, u);
  const 变 = Math.floor(Number(v) || 0);
  if (!变) return 旧;
  // 2.9.10（需求 4）：正向加分受每日上限约束（超出不发放不补发）；扣分不受限
  let 实变 = 变;
  if (实变 > 0 && 旧 < 信用上限) {
    const 余 = Math.max(0, 信用每日上限 - 日取量(ctx, u, "信用已获"));
    实变 = Math.min(实变, 余);
    if (实变 <= 0) return 旧;   // 今日信用加分已满 → 直接不发放（也不转奖励分）
    日加量(ctx, u, "信用已获", 实变);
  }
  const 新 = Math.max(0, Math.min(信用上限, 旧 + 实变));
  if (新 === 旧) {
    // 2.9.8（需求 5）：主分已满 100 且还在加分 → 溢出部分转入奖励分（2.9.10：受 25/日 限）
    if (变 > 0) {
      const r余 = Math.max(0, 奖励分每日上限 - 日取量(ctx, u, "奖励已获"));
      const r实 = Math.min(变, r余);
      if (r实 > 0) { 加奖励分(ctx, u, r实, S(事由)); 日加量(ctx, u, "奖励已获", r实); }
      记信用事件(ctx, u, S(事由) + (r实 > 0 ? "（主分已满，奖励分 +" + r实 + "）" : "（主分已满，今日奖励分已满，未发放）"), 0);
    }
    return 旧;
  }
  dset(ctx, P.信用分, u, 新);
  pushLog(ctx, u, "信用分 " + 旧 + " → " + 新 + "（" + S(事由) + "）");
  记信用事件(ctx, u, S(事由), 新 - 旧);
  // 2.9.12（需求 4）：扣信用分联动奖励分 —— 实际每扣 1 信用分同时从奖励分拿走 100；
  //   当前奖励分不满 100（扣不到完整 100）时直接归零（不留零头）。流水记两笔（信用变动 + 奖励分联动）。
  if (新 < 旧) {
    let r = 取奖励分(ctx, u);
    const 扣前 = r;
    for (let i = 0; i < 旧 - 新 && r > 0; i++) r = r >= 100 ? r - 100 : 0;
    if (r !== 扣前) {
      dset(ctx, P.奖励分, u, r);
      记信用事件(ctx, u, "扣分联动：奖励分 -" + (扣前 - r) + "（每 -1 信用分联动 -100，不满 100 归零）", 0);
    }
  }
  // 主分没涨满但超出 100 的那部分也转奖励分（2.9.10：受 25/日 限）
  const 溢 = 旧 + 实变 - 新;
  if (溢 > 0) {
    const r余 = Math.max(0, 奖励分每日上限 - 日取量(ctx, u, "奖励已获"));
    const r实 = Math.min(溢, r余);
    if (r实 > 0) { 加奖励分(ctx, u, r实, S(事由)); 日加量(ctx, u, "奖励已获", r实); }
  }
  return 新;
}


