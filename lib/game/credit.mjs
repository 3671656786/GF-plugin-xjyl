export function 读贷款(ctx, u) {
  const v = dget(ctx, P.贷款, u, null);
  if (!v || typeof v !== "object") return null;
  // 3.1.3：老存档补默认字段（已扣超期 = 首次逾期的 5 分是否已扣）
  if (v.已扣超期 === undefined || v.已扣超期 === null) v.已扣超期 = 0;
  if (v.已扣逾期 === undefined || v.已扣逾期 === null) v.已扣逾期 = 0;
  return v;
}


export function 写贷款(ctx, u, L) { dset(ctx, P.贷款, u, L); }


export function 现有贷款(ctx, u) { const L = 读贷款(ctx, u); return L && Number(L.余额) > 0 ? L : null; }


/* 3.1.3 阶梯计息：第 N 天按 N × 0.01% / 小时计息（超 14 天按 0.15% / 小时）
 * 每次只推进「又满了一个整小时」的那段，逐小时套用当天的利率 → 跨天时能自动分段。
 * 借出当天算第 1 天（借时起 24 小时内都是第 1 天的利率）。
 */
export function 贷款计息(ctx, u, 现在) {
  const L = 读贷款(ctx, u);
  if (!L || !(Number(L.余额) > 0)) return L;
  const now = Number(现在) || Date.now();
  const 上次 = Number(L.上次计息) || Number(L.借时) || now;
  const 借时 = Number(L.借时) || 上次;
  let 余额 = Number(L.余额) || 0;
  let 利息 = Number(L.利息) || 0;
  let 游标 = 上次;
  let 新息 = 0;
  // 最多推进 400 小时（约 16 天），防止长期不结算时一次算太多
  for (let i = 0; i < 400; i++) {
    if (游标 + 3600000 > now) break;
    const 天 = Math.floor((游标 - 借时) / 86400000) + 1;   // 第几天（借出当天 = 第 1 天）
    const 率 = 贷款阶梯利率(天);
    新息 += Math.floor(余额 * 率);
    游标 += 3600000;
  }
  if (游标 > 上次) {
    L.利息 = 利息 + 新息;
    L.上次计息 = 游标;
    写贷款(ctx, u, L);
  }
  return L;
}


/* 3.1.3 逾期：借出超过 14 天（到期）即进入逾期
 *   · 利率：一律按 0.15% / 小时（阶梯利率函数在第 14 天后自动返回超期利率）
 *   · 信用分：首次进入逾期**一次性扣 5 分**；之后每多逾期一天再扣 1 分（同一天只扣一次）
 */
export function 结算逾期(ctx, u, 现在) {
  const L = 现有贷款(ctx, u);
  if (!L) return 0;
  const now = Number(现在) || Date.now();
  const 到期 = Number(L.到期) || 0;
  if (!到期 || now <= 到期) return 0;
  // 逾期天 = 已经走完的完整天数（逾期不到 1 天也算第 1 天）
  const 逾期天 = Math.max(1, Math.floor((now - 到期) / 86400000));
  const 已扣 = Math.max(0, Number(L.已扣逾期) || 0);
  let 扣分 = 0;
  if (!L.已扣超期) {
    L.已扣超期 = 1;
    扣分 += 贷款超期扣分;
  }
  if (逾期天 > 已扣) {
    扣分 += 逾期天 - 已扣;
    L.已扣逾期 = 逾期天;
  }
  if (扣分 > 0) {
    写贷款(ctx, u, L);
    加信用分(ctx, u, -扣分, "贷款逾期（超过 " + 贷款阶梯天数 + " 天）");
    return 扣分;
  }
  return 0;
}


export function 贷款概况(ctx, u, 现在) {
  结算逾期(ctx, u, 现在);
  const L = 贷款计息(ctx, u, 现在);
  const now = Number(现在) || Date.now();
  if (!L || !(Number(L.余额) > 0)) return { 有: false, 本金: 0, 余额: 0, 利息: 0, 欠款: 0, 借时: 0, 到期: 0, 剩余毫秒: 0, 逾期天: 0 };
  const 到期 = Number(L.到期) || 0;
  const 余额 = Math.max(0, Math.floor(Number(L.余额) || 0));
  const 利息 = Math.max(0, Math.floor(Number(L.利息) || 0));
  return {
    有: true, 本金: Math.floor(Number(L.本金) || 0), 余额: 余额, 利息: 利息, 欠款: 余额 + 利息,
    借时: Number(L.借时) || now, 到期: 到期, 剩余毫秒: Math.max(0, 到期 - now),
    逾期天: 到期 && now > 到期 ? Math.max(1, Math.floor((now - 到期) / 86400000)) : 0
  };
}


/* ============================================================
 * 2.9.13（U6）：进程内 per-key 串行队列（promise 链互斥）
 * ------------------------------------------------------------
 * · 同键操作严格串行：前一个完成（成功或失败）后，下一个才开始 —— 杜绝「读→算→写」交错丢更新。
 * · 快路径：当前没有等待中的异步任务时，fn 同步执行、同步返回值 —— 现有同步调用方语义完全不变；
 *   Node 单进程内同步代码本就不会被打断，快路径天然原子。
 *   有异步任务（返回 Promise）持锁/排队期间，同键后续操作（哪怕同步进来）一律排队等它。
 * · ⚠ 并发边界（重要）：本工具只保证 **单进程** 串行。QQ 机器人单实例部署足够；
 *   真正多进程部署同一 dataPath 需要外部锁（文件锁 / Redis 等），本插件不做（见架构注释）。
 * ============================================================ */
export const __串行锁表 = new Map();

   // 键 → { 尾: Promise, 深度: 排队/执行中的异步任务数 }
export function 串行锁(键, fn) {
  let 槽 = __串行锁表.get(键);
  if (!槽) { 槽 = { 尾: Promise.resolve(), 深度: 0 }; __串行锁表.set(键, 槽); }
  槽.深度 += 1;
  const 本轮 = 槽.尾.then(() => fn(), () => fn());
  const 收尾 = () => {
    槽.深度 -= 1;
    // 挂在「本轮」一级反应上：先于调用方 await 恢复执行，保证 await 回来时快路径已恢复
    if (槽.深度 <= 0 && __串行锁表.get(键) === 槽) __串行锁表.delete(键);
  };
  本轮.then(收尾, 收尾);
  槽.尾 = 本轮.then(() => {}, () => {});
  return 本轮;
}


export function 过队列(键, fn) {
  const 槽 = __串行锁表.get(键);
  if (!槽 || 槽.深度 <= 0) return fn();   // 快路径：无异步任务排队 → 同步执行（同步返回值）
  return 串行锁(键, fn);                   // 有异步任务 → 排队（返回 Promise）
}


