/* ---------- 3.0.0（需求 21）：宠物自动干活的薄封装 ----------
 * 宠物（lib/game/pet.mjs）需要「不吭声地」收菜 / 播种，而下面两个面板函数会 reply。
 * 把「收菜 / 种一片」的核心抽成 静默收菜 / 静默种菜（不发消息、只改存档并返回结果），
 * `收获` / `一键种菜` 改成调用它们后再说话 —— 存档写入、事件计数、农场经验、回复文案与拆分前一致。
 * 约定：静默函数只按 `最多` 截断块数，不做任何权限/提示判断，提示一律由调用方负责。
 */
export function 静默收菜(ctx, u, 最多) {
  const 地 = 读农场(ctx, u);
  const now = Date.now();
  const 限 = 最多 === undefined || 最多 === null ? 地.length : Math.max(1, Math.floor(Number(最多) || 1));
  const 得 = {};
  let 收了 = 0, 农经验 = 0;
  for (let i = 0; i < 地.length && 收了 < 限; i++) {
    const g = 地[i];
    if (!g || now < g.成熟) continue;
    得[g.作物] = (得[g.作物] || 0) + g.产量;
    // 2.9.0（需求 4）：收菜按作物档次给农场经验（分钟越长越多）
    const it0 = 作物找(g.作物);
    农经验 += 农场收菜经验(it0 ? it0.分钟 : 3);
    地[i] = null;
    收了 += 1;
  }
  let 农升 = { 等级: 读农场成长(ctx, u).等级, 经验: 0, 升级: 0, 解锁地: 0 };
  if (收了) {
    存农场(ctx, u, 地);
    tInc(ctx, u, "收菜");
    tInc(ctx, u, "使用道具");
    农升 = 加农场经验(ctx, u, 农经验);
    for (const k of Object.keys(得)) giveItem(ctx, u, k, 得[k]);
  }
  return { 地: 地, 块: 收了, 得: 得, 农经验: 农经验, 农升: 农升 };
}


