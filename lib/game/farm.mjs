// 灰块：这里内联一份，避免 farm ↔ cook 循环依赖（cook.mjs 已经 import 了本文件的作物表）
function 灰块(lines) {
  return (Array.isArray(lines) ? lines : [lines])
    .map((x) => { const t = String(x === undefined || x === null ? "" : x); return t === "" ? ">" : "> " + t; })
    .join("\n");
}
// 3.3.7：黑白混排（分区标题黑加粗 / 数据灰引用）—— 同样内联避免循环依赖
function 灰混(parts) {
  return (Array.isArray(parts) ? parts : []).map((x) => {
    const t = String((x && x[0]) === undefined || (x && x[0]) === null ? "" : x[0]);
    const 是灰 = !(x && x[1] === false);
    if (!是灰) return "**" + t + "**";
    return t === "" ? ">" : "> " + t;
  }).join("\n");
}


