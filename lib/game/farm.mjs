/* ---------- 2.5.52 日常玩法经验「随等级成长」 ----------
 * 问题：打坐 / 探索 / 挖矿 / 打工 / 钓鱼 / 做菜 的经验是**写死的固定值**（如打坐 80~200 + 等级×2），
 *      而升级需求是指数级涨的（30 级 5,000 → 90 级 50 万 → 300 级 1,180 万），
 *      于是后期这些玩法给的经验连 0.01% 级都不到，等于白做 —— 「升级太难」的主因之一。
 * 改法：**低于 30 级完全不变**；30 级起按「当前等级升满所需经验 × 占比」给，
 *      并且取 `max(原固定值, 成长值)`，所以只升不降、老手感不丢。
 *   · 占比按各玩法的**可获得频次**分别设定（打坐 10 次/天 → 高占比；探索 5 秒一次 → 低占比）
 *   · 调平衡只改下面「日常经验占比」这一张表
 */
export const 日常经验占比 = {
  打坐: 0.02,      // 2.0%/次，10 次/天 ≈ 20% 级
  探索: 0.0001,    // 0.01%/次，单次指令最多 1000 次（5 秒冷却，可长期刷）
  挖矿: 0.003,     // 0.3%/次（受血量限制）
  打工: 0.01,      // 1.0%/次（10 分钟冷却）
  钓鱼: 0.0005,    // 0.05%/竿（受鱼饵限制）
  做菜: 0.0005,    // 0.05%/份（受材料限制）
  副本: 0         // 副本 / BOSS / 天下楼走各自的高额奖励，不参与本表
};


// 基础值 → 成长后的经验（只升不降）
export function 日常经验(基础, 等级, 类别) {
  const 基 = Math.max(0, Math.round(Number(基础) || 0));
  const L = Math.max(1, Math.floor(Number(等级) || 1));
  const 占 = Number(日常经验占比[类别]) || 0;
  if (L <= LV_BASE || 占 <= 0) return 基;                   // 30 级（0 转上限）前完全不变
  const 成长 = Math.round(经验锚点(L) * 占);   // 2.9.14：奖励侧挂经验锚点（旧曲线），数值不随门槛上调
  return Math.max(基, 成长);
}



