  const 有 = hasItem(ctx, u, it.种子);
  const 限 = 最多 === undefined || 最多 === null ? Infinity : Math.max(1, Math.floor(Number(最多) || 1));
  const 用 = Math.min(空, 有, 限);
  if (!用) return { ok: false, 原因: "缺种子", it: it, 地: 地, 填: 0, 空: 空, 农升: null };
  takeItem(ctx, u, it.种子, 用);
  const now = Date.now();
