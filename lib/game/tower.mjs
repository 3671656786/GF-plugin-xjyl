// 2.5.51（1000 层适配）：这两个函数原来分母是 (99-30)，层数一过 99 就会算出
//   「30 倍承伤 / 390% 煞气」这种崩坏值。现在 30~99 层保持原曲线，100 层起改用对数压缩并封顶：
//   承伤系数：30 层 1.0 → 99 层 3.0 → 300 层 4.5 → 600 层 5.3 → 1000 层 6.0
//   煞气占比：30 层 40% → 99 层 65% → 1000 层 80%（封顶 80%）
export function 塔内承伤系数(层) {
  const L = Math.max(1, Math.min(天下楼层数, Number(层) || 1));
  if (L < 30) return 0;
  if (L <= 天下楼经典层) return 1.0 + 2.0 * ((L - 30) / (天下楼经典层 - 30));
  return 3.0 + 3.0 * Math.log10(L / 天下楼经典层);
}


export function 塔内煞气占比(层) {
  const L = Math.max(1, Math.min(天下楼层数, Number(层) || 1));
  if (L < 30) return 0;
  if (L <= 天下楼经典层) return 0.4 + 0.25 * ((L - 30) / (天下楼经典层 - 30));
  return Math.min(0.8, 0.65 + 0.15 * Math.log10(L / 天下楼经典层));
}


export function 天下楼目标承伤(层, 血上限) { return Math.round(Math.max(0, Number(血上限) || 0) * 塔内承伤系数(层)); }


