/* 我方一次完整出手：主伤害（含技能倍率）+ 追击 → 合并成「一次结算」后统一截断 + 吸血 + 守方「反击」打回自己
 * 返回值只用于日志展示，扣血已经写回 rec。
 * 2.9.12：战报格式统一 —— 双向同格式，主体视角是「你」：
 *   ✦ 普通行 / ✧ 暴击·真伤行；追击带对主伤害的百分比；吸血「你吸了X N 点血」；
 *   闪击 = 弹反宣告 + 闪击伤害；反击 = 「发动了反击，减免了N伤害，并对X造成了N伤害」。 */
/* 3.0.0：本函数已**废弃** —— 出手统一走 lib/game/combat.mjs 的 玩家出手()
 *   （那里对反击 / 反伤做了封顶，避免「未截断伤害反弹把自己秒杀」的老 bug）。
 *   这里仅保留导出做向后兼容；新代码不要再调用它。
 */
export function 我方出手(rec, d, 倍率, 类型, 技能名) {
  const r = 我方伤害(rec, d);
  const 行 = [];
  const 敌名 = S(rec.名称);
  let 伤 = 0;
  if (r.闪避) {
    行.push("✦" + 敌名 + "闪避成功，你造成了0 伤害");
  } else {
    // 2.9.3：主伤害 + 追击先相加，再整体裁到「单刀上限」（不再各自裁一次、合计最多 2 倍上限）
    const 主 = Math.max(1, Math.round(r.dmg * (倍率 || 1)));
    const 追 = r.追击 > 0 ? Math.round(r.追击) : 0;
    const 合计 = 主 + 追;
    伤 = 单刀截断(rec, 类型, 合计, 行);
    const 实 = 实际伤害(rec, 伤);
    rec.bhp = Math.max(0, rec.bhp - 实);
    rec.累计伤害 = (Number(rec.累计伤害) || 0) + 实;
    // 主伤害行 + 追击行（追击 % = 追击 / 主伤害）
    const 显示追 = Math.min(追, 伤);
    const 显示主 = Math.max(1, 伤 - 显示追);
    行.push((r.暴 ? "✧" : "✦") + "你对" + 敌名 + "造成了 " + 大数(显示主)
      + (r.真伤 ? (r.暴 ? " 点真实暴击伤害" : " 点真实伤害") : (r.暴 ? " 暴击伤害" : " 伤害"))
      + (r.抗暴 ? "（被抗暴）" : "") + (实 < 伤 ? "（溢出，击杀）" : ""));
    if (显示追 > 0) 行.push("✦你对" + 敌名 + "造成了 " + 大数(显示追) + " 追击伤害(" + Math.round(显示追 / 显示主 * 100) + "%)");
    const 进阶 = 推进敌方阶段(rec, rec.名称);
    if (进阶.变化) 行.push(进阶.提示);
  }
  // 吸血（单次 ≤ 血量上限 30%，伤害结算里已经裁过）
  if (r.吸血 > 0) {
    const 回 = Math.min(r.吸血, Math.max(0, rec.hpMax - rec.hp));
    if (回 > 0) {
      rec.hp = Math.min(rec.hpMax, rec.hp + 回);
      行.push("✦你吸了" + 敌名 + " " + 大数(回) + " 点血");
    }
  }
  // 守方「反击 / 闪击 / 反伤」打回自己身上
  for (const f of (r.反伤 || [])) {
    rec.hp = Math.max(0, rec.hp - f.伤害);
    rec.累计受伤 = (Number(rec.累计受伤) || 0) + f.伤害;
    if (f.类型 === "闪击") 行.push("✦" + 敌名 + "发动了闪击进行弹反", (f.暴 ? "✧" : "✦") + 敌名 + "对你造成了 " + 大数(f.伤害) + " 点闪击" + (f.暴 ? "真实暴击" : "") + "伤害");
    else if (f.类型 === "反击") 行.push("✦" + 敌名 + "发动了反击，减免了" + 大数(f.伤害) + "伤害，并对你造成了" + 大数(f.伤害) + "伤害");
    else 行.push("✦" + 敌名 + "发动了反伤，你受到 " + 大数(f.伤害) + " 反弹伤害");
  }
  return { 伤: 伤, 闪避: r.闪避, 暴: r.暴, 吸血: r.吸血, 行: 行 };
}


