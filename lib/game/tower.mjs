// 2.5.31 数值重做：难度与奖励都随层数**平滑加速**（1~30 层简单档，越往后越难越富）
//   · 推荐等级 ≈ 3 × 层数（99 层 ≈ 297 级，正好覆盖满级内容）
//   · 力 = 同推荐段位 BOSS 的 62%（塔无入场费 / 无冷却，所以单体强度略低于同级 BOSS）
//   · 血量系数随层数变大（2.4 → 13.3），让「血厚」在高层真正起作用（低层仍是几刀斩）
//   · 奖励档 = 0.25 + 1.8 ×(L/99)²：1 层 0.25 / 30 层 0.42 / 60 层 0.91 / 99 层 2.05
// 2.5.51（扩层适配）：L ≤ 99 全部原样；L > 99 用压缩曲线延伸，避免数值爆炸
//   · 奖档：99 层 2.05 → 150 层 2.16 → 200 层 2.24 → 250 层 2.29（对数压缩）
//   · 推荐等级：99 层 297 → 150 层 366 → 200 层 422 → 250 层 472（√ 压缩）
export function 天下楼奖档(层) {
  const L = Math.max(1, Math.min(天下楼层数, Number(层) || 1));
  if (L <= 天下楼经典层) return Math.round((0.25 + 1.8 * Math.pow(L / 天下楼经典层, 2)) * 100) / 100;
  return Math.round((2.05 + 0.5 * Math.log10(L / 天下楼经典层)) * 100) / 100;
}


export function 天下楼推荐等级(层) {
  const L = Math.max(1, Math.min(天下楼层数, Math.floor(Number(层) || 1)));
  if (L <= 天下楼经典层) return Math.max(1, Math.round(3 * L));
  return Math.max(1, Math.round(3 * 天下楼经典层 * Math.sqrt(L / 天下楼经典层)));
}


// 2.5.51：怪物的「成长等效层」—— 100 层起用 √ 压缩，让 1000 层的血量/攻击/星核不会失控
//   （L ≤ 99 时恒等于 L，所以经典层的数值完全不变）
export function 天下楼成长层(层) {
  const L = Math.max(1, Math.min(天下楼层数, Number(层) || 1));
  if (L <= 天下楼经典层) return L;
  return 天下楼经典层 * Math.sqrt(L / 天下楼经典层);
}


