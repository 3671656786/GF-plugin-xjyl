/* BOSS 血量系数（段位纯函数）：段 1 → ×2.8，段 500 → ×1.9，恒在 (1.0, 4.4) 之间
 * —— 既保证「同段 BOSS 血 > 副本」，又永远低于塔（×4.4），三段单调不交叉。 */
export function BOSS血系数(段) {
  const s = Math.max(1, Math.min(500, Number(段) || 1));
  return Math.round((2.8 - 0.9 * (s / 500)) * 100) / 100;
}


