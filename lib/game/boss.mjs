export function BOSS攻倍率(段) {
  // 2.10.0（需求 4.1/4.2）：**BOSS 表已不再用这张表算攻击**（改为 三档难度系数.BOSS.攻 = 1.1 的段位纯系数）。
  //   保留导出只是兼容 misc.mjs / 面板 / 旧测试的引用与历史标定记录（下方表体逐段实测数据仍可查）。
  const s = Number(段) || 1;
  const exact = BOSS攻倍率分段表[s];
  if (exact) return exact;
  const pts = BOSS攻倍率曲线点;
  if (s <= pts[0][0]) return pts[0][1];
  const last = pts[pts.length - 1];
  if (s >= last[0]) return last[1];
  for (let k = 1; k < pts.length; k++) {
    if (s <= pts[k][0]) {
      const a = pts[k - 1], b = pts[k];
      return a[1] + (b[1] - a[1]) * (s - a[0]) / (b[0] - a[0]);
    }
  }
  return last[1];
}


