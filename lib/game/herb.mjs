// 今日产出进度行（面板顶部）：X/上限 血 + 剩余额度 + 上限怎么涨
export function 今日行(园) {
  const 上 = 园日上限(园);
  const 已 = 园.每日产出 ? 园.每日产出.已产血 : 0;
  const 剩 = Math.max(0, 上 - 已);
  const 比 = 上 > 0 ? Math.min(1, 已 / 上) : 1;
  const 块 = Math.round(比 * 10);
  const 条 = "[" + "█".repeat(块) + "░".repeat(10 - 块) + "]";
  return "**今日产出**：" + 条 + " " + kfmt(已) + "/" + kfmt(上) + " 血（剩 " + kfmt(剩) + "）"
    + (已 >= 上 ? " · ⛔ 今日已满，明日 0 点重置" : " · 明日 0 点重置");
}


