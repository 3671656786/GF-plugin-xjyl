// 自动补种：把空田按偏好种上（可自动买种）→ 返回 { 种了几块, 买了什么, 花了多少, 提示 }
export function 自动播种(ctx, u, 园) {
  const 偏 = 园.偏好 || {};
  if (!偏.灵种 || !灵种找(偏.灵种)) return { 种了几块: 0, 花了多少: 0, 提示: "" };
  const 灵 = 灵种找(偏.灵种);
  let 种了几块 = 0, 花了多少 = 0, 买了 = 0, 缺钱 = false;
  for (let i = 1; i <= 园.开垦; i++) {
    if (园.田[i - 1]) continue;                 // 已有作物
    const r = 种一块田(ctx, u, 园, i, 灵.名, true);
    if (r.ok) {
      种了几块 += 1;
      if (r.自动购买) { 花了多少 += r.花费; 买了 += 1; }
    } else if (r.原因 === "星羽不足") {
      缺钱 = true;
      break;                                    // 钱不够就停，别把其他田也卡住
    } else if (r.原因 === "无种子") {
      break;
    }
  }
  const 提示 = 种了几块
    ? "已自动补种 **" + 种了几块 + "** 块田（" + 灵.名 + "）" + (买了 ? "，自动买种 " + 买了 + " 包，花费 " + kfmt(花了多少) + " 星羽" : "")
  + (缺钱 ? " · 星羽不足，部分田未补种" : "")
  : (缺钱 ? "星羽不足，自动补种失败（需要 " + kfmt(灵种星羽价(灵)) + " 星羽）" : "");
  return { 种了几块: 种了几块, 花了多少: 花了多少, 提示: 提示 };
}


// 自动炼药：偏好里设了药方且药材够 → 自动开炼（内部用，不发消息）
export function 自动炼药(ctx, u, 园) {
  const 偏 = 园.偏好 || {};
  if (!偏.药方 || !药方找(偏.药方)) return { 炼了: false, 提示: "" };
  const 药方 = 药方找(偏.药方);
  const 柜 = 园.药柜.药材 || {};
  for (const m of 药方.需) {
    if ((柜[m.名] || 0) < (m.数 || 0)) return { 炼了: false, 提示: "" };
  }
  const 轮 = Math.min(单次轮数硬上限, 1);
  const 每轮 = 每轮份数(园.炼药.等级, 炼药等级上限);
  let 轮数 = 0;
  for (let i = 0; i < 轮; i++) {
    for (const m of 药方.需) {
      const 有 = (园.药柜.药材[m.名] || 0) - (m.数 || 0);
      if (有 < 0) return { 炼了: 轮数 > 0, 提示: 轮数 ? "已自动炼 " + 轮数 + " 轮 " + 药方.名 : "" };
      园.药柜.药材[m.名] = 有;
    }
    园.药柜.成药[药方.名] = (园.药柜.成药[药方.名] || 0) + 每轮;
    轮数 += 1;
  }
  return { 炼了: 轮数 > 0, 轮数: 轮数, 药方: 药方.名, 份数: 每轮, 提示: 轮数 ? "已自动炼 **" + 轮数 + "** 轮 " + 药方.名 + "（+" + 每轮 + " 份）" : "" };
}


