/* ============================================================
 * 3.1.3 浇水 / 播种偏好 / 自动播种
 * ------------------------------------------------------------
 * · 浇水：每块田每 30 分钟可浇一次，浇一次随机缩短剩余生长时间的 5%~10%；
 * · 播种偏好：设置「默认灵种」后，收获腾出的空田会自动补种；
 *   种子不够时**自动买种**（扣星羽，需要提前存钱；钱不够就跳过并提示）；
 * · 炼药偏好：设置「默认药方」后，药柜里药材够了就自动开始炼药。
 * ============================================================ */

// 单块田能否浇水（生长中 + 冷却好了）
export function 可浇水(田块, now) {
  if (!田块) return false;
  if (now >= 田块.成熟) return false;             // 已成熟不用浇
  const 上次 = Number(田块.浇水) || 0;
  return now - 上次 >= 浇水冷却毫秒;
}


// 浇一次水：返回 { ok, 缩短秒, 比例 } 或 { ok:false, 原因, 剩余毫秒 }
export function 浇水一块(田块, now) {
  if (!田块) return { ok: false, 原因: "空地" };
  if (now >= 田块.成熟) return { ok: false, 原因: "已成熟" };
  const 上次 = Number(田块.浇水) || 0;
  const 等 = 浇水冷却毫秒 - (now - 上次);
  if (等 > 0) return { ok: false, 原因: "冷却中", 剩余毫秒: 等 };
  const 剩 = 田块.成熟 - now;
  const 比例 = 浇水缩短比例();
  const 缩短 = Math.floor(剩 * 比例);
  田块.成熟 = Math.max(now + 1000, 田块.成熟 - 缩短);
  田块.浇水 = now;
  return { ok: true, 缩短秒: Math.round(缩短 / 1000), 比例: 比例 };
}


// 种一块田（内部）：种子够就种，不够则按需自动买种
// 返回 { ok, 灵种, 产量, 自动购买, 花费 } 或 { ok:false, 原因 }
export function 种一块田(ctx, u, 园, 号, 灵名, 可自动买) {
  const 灵 = 灵种找(灵名);
  if (!灵) return { ok: false, 原因: "无此灵种" };
  const 仓 = 读种子仓(ctx, u);
  let 自动购买 = false, 花费 = 0;
  if ((仓.种[灵.名] || 0) < 1) {
    if (!可自动买) return { ok: false, 原因: "无种子" };
    const 单价 = 灵种星羽价(灵);
    const 有 = dn(ctx, P.星羽, u, 0);
    if (有 < 单价) return { ok: false, 原因: "星羽不足", 需要: 单价, 有: 有 };
    addCoin(ctx, u, -单价);
    花费 = 单价;
    自动购买 = true;
    仓.种[灵.名] = (仓.种[灵.名] || 0) + 1;
    写种子仓(ctx, u, 仓);
  }
  const now = Date.now();
  const 产 = 田产量(灵.产量, 园.田等级[号 - 1]);
  仓.种[灵.名] -= 1;
  写种子仓(ctx, u, 仓);
  园.田[号 - 1] = { 灵种: 灵.名, 种下: now, 成熟: now + 灵.分钟 * 60000, 产量: 产, 浇水: 0 };
  return { ok: true, 灵种: 灵.名, 产量: 产, 自动购买: 自动购买, 花费: 花费 };
}


