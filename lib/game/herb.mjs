export function 剩余(ms) {
  const s = Math.max(0, Math.ceil(Number(ms) / 1000));
  const m = Math.floor(s / 60);
  if (m <= 0) return s + " 秒";
  if (m < 60) return m + " 分" + (s % 60 ? " " + (s % 60) + " 秒" : "");
  return Math.floor(m / 60) + " 小时 " + (m % 60) + " 分";
}


// 灵石余额（星羽 ÷ 2）—— 3.1.3 起界面不再展示，仅保留兼容旧调用
export function 灵石余额(ctx, u) {
  return Math.floor(Math.max(0, dn(ctx, P.星羽, u, 0)) / 汇率.灵石兑星羽);
}


// 田号参数：只认 1~8（越界返回 0，由调用方给提示）
export function 解析田号(键) {
  const s = S(键);
  if (!/^[1-9]$/.test(s)) return 0;
  const i = Number(s);
  return i >= 1 && i <= 田上限 ? i : 0;
}


// 田块一行文案（面板 / 收获提示共用）
// 3.1.3：加上浇水状态（可浇 / 冷却中）与催熟、复原快捷操作
export function 田行文案(园, i, now) {
  const 号 = i + 1;
  const 等 = 园.田等级[i] || 1;
  if (号 > 园.开垦) {
    const 费 = 开垦费(号);
    return "🔒 田" + 号 + " · 未开垦（`药园开垦` 需 " + kfmt(费.星羽) + " 星羽）";
  }
  const s = 园.田[i];
  if (!s) return "🟫 田" + 号 + " · Lv." + 等 + " 空地（产量 ×" + 田产量倍率(等).toFixed(1) + "，可种）";
  const 灵 = 灵种找(s.灵种);
  const 名 = 灵 ? 灵.药材 : "药材";
  const 浇 = 浇水状态(s, now);
  if ((now || Date.now()) >= s.成熟) return "✅ 田" + 号 + " · Lv." + 等 + " · 【" + 名 + "】×" + s.产量 + " 已成熟（`药园收 " + 号 + "`）";
  return "🌿 田" + 号 + " · Lv." + 等 + " · " + s.灵种 + " → " + 名 + " ×" + s.产量 + " · 还需 **" + 剩余(s.成熟 - (now || Date.now())) + "**" + 浇;
}


// 浇水状态后缀：可浇 / 冷却中（3.1.3）
export function 浇水状态(田块, now) {
  if (!田块) return "";
  const t = now || Date.now();
  if (t >= 田块.成熟) return "";
  const 上次 = Number(田块.浇水) || 0;
  const 等 = 浇水冷却毫秒 - (t - 上次);
  if (等 > 0) return " · 🚿 浇水冷却中（约 " + 剩余(等) + "）";
  return " · 🚿 可浇水";
}


