// 今日（本地时区）的日期串，用于每日产出上限的跨天重置
export function 今天() { return ymd(Date.now()); }


// 每日产出兜底：跨天自动归零（日期不是今天 → 已产血清零）
export function 规范每日产出(源) {
  const o = 源 && typeof 源 === "object" ? 源 : {};
  const 日 = S(o.日期);
  const 今 = 今天();
  if (日 !== 今) return { 日期: 今, 已产血: 0 };
  return { 日期: 今, 已产血: Math.max(0, Math.round(Number(o.已产血) || 0)) };
}


// 灵田均级（只算已开垦的田）—— 每日血上限的输入之一
export function 灵田均级(园) {
  const 已 = Math.max(1, Math.min(田上限, Math.floor(Number(园 && 园.开垦) || 田起步)));
  let 共 = 0;
  for (let i = 0; i < 已; i += 1) 共 += Math.max(1, Math.min(田等级上限, Math.floor(Number(园.田等级[i]) || 1)));
  return 共 / 已;
}


// 这个园子当前能产出多少血/天（面板与判定共用）
export function 园日上限(园) { return 每日血上限(灵田均级(园), 园 && 园.炼药 ? 园.炼药.等级 : 1); }


// 今日还能产多少血（≥0）
export function 园今日剩余(园) {
  const 上 = 园日上限(园);
  const 已 = 园 && 园.每日产出 ? 园.每日产出.已产血 : 0;
  return Math.max(0, 上 - 已);
}


// 数量表兜底：只保留正整数、丢掉 0/负数/脏键（版本升级后清脏数据也走这里）
function 规范数量(源) {
  const out = {};
  if (源 && typeof 源 === "object") {
    for (const k of Object.keys(源)) {
      const 名 = S(k);
      const v = Math.floor(Number(源[k]) || 0);
      if (名 && v > 0) out[名] = (out[名] || 0) + v;
    }
  }
  return out;
}


// 炼药等级兜底：夹 1~10，经验溢出自动折级（防止上限调整 / 手改档卡死）
// 1.1.0：经验按「份数」给，可能是 0.23 这种小数 → 保留 2 位（低档药也不会被截成 0 经验）
export function 规范炼药(源) {
  const o = 源 && typeof 源 === "object" ? 源 : {};
  let 等级 = Math.max(1, Math.min(炼药等级上限, Math.floor(Number(o.等级) || 1)));
  let 经验 = Math.max(0, Math.round((Number(o.经验) || 0) * 100) / 100);
  while (等级 < 炼药等级上限 && 经验 >= 炼药升级需经验(等级)) {
    经验 -= 炼药升级需经验(等级);
    等级 += 1;
  }
  经验 = Math.round(经验 * 100) / 100;
  if (等级 >= 炼药等级上限) 经验 = Math.min(经验, 炼药升级需经验(炼药等级上限));
  return { 等级: 等级, 经验: 经验 };
}


// 读药园：缺字段全部补默认（开垦至少 1 块、田固定 8 格、等级夹 1~10）
export function 读药园(ctx, u) {
  const raw = dget(ctx, P药园, u, null);
  const o = raw && typeof raw === "object" ? raw : {};
  const 开垦 = Math.max(田起步, Math.min(田上限, Math.floor(Number(o.开垦) || 田起步)));
  const 田原 = Array.isArray(o.田) ? o.田 : [];
  const 级原 = Array.isArray(o.田等级) ? o.田等级 : [];
  const 田 = [], 田等级 = [];
  for (let i = 0; i < 田上限; i++) {
    田等级.push(Math.max(1, Math.min(田等级上限, Math.floor(Number(级原[i]) || 1))));
    const s = 田原[i];
    if (s && s.灵种 && 灵种找(s.灵种)) {
      田.push({
        灵种: S(s.灵种),
        种下: Number(s.种下) || 0,
        成熟: Number(s.成熟) || 0,
        产量: Math.max(1, Math.min(单田产量上限, Math.floor(Number(s.产量) || 1))),
        浇水: Number(s.浇水) || 0        // 3.1.3：上次浇水时间（0 = 没浇过）
      });
    } else {
      田.push(null);
    }
  }
  const 柜 = o.药柜 && typeof o.药柜 === "object" ? o.药柜 : {};
  // 3.1.3：播种偏好（指定种什么灵种，空田自动播种；没种子自动购买）+ 炼药偏好（做什么药）
  const 偏 = o.偏好 && typeof o.偏好 === "object" ? o.偏好 : {};
  return {
    版本: S(o.版本) || 版本药园,
    开垦: 开垦,
    田: 田,
    田等级: 田等级,
    炼药: 规范炼药(o.炼药),
    偏好: { 灵种: S(偏.灵种) || "", 药方: S(偏.药方) || "" },
    药柜: { 药材: 规范数量(柜.药材), 成药: 规范数量(柜.成药) },
    每日产出: 规范每日产出(o.每日产出)
  };
}


