/* ---------- 2.9.2 插件内置更新日志 ----------
 * 文档里的 `## 版本号` 章节由 读公告() 解析；这一条直接写在代码里，
 * 保证「插件升了版本但文档还没来得及写」时玩家发 `更新公告` 也能看到最新的改动。
 * 新版本往上加一条即可（数组第一条 = 最新）。
 */


export function 读公告(ctx) {
  const 条 = 更新日志.map((x) => ({ 标题: x.标题, 版本: x.版本, 正文: x.正文 }));
  try {
    // 3.1.7：更新公告与插件文档分离 —— 历史公告在 `更新公告.md`，
    //   `插件文档.md` 只留实装规则速查（不再混在一起，文档不再越堆越乱）。
    //   读不到新文件时回退读旧文件，兼容老版本布局。
    let p = 解析插件相对路径(ctx, "更新公告.md");
    if (!p || !fs.existsSync(p)) p = 解析插件相对路径(ctx, "插件文档.md");
    if (!p || !fs.existsSync(p)) return 条;
    const 行 = fs.readFileSync(p, "utf8").split(/\r?\n/);
    let 当前 = null;
    for (const L of 行) {
      const m = L.match(/^##\s+(.+)$/);
      if (m) {
        const 标 = m[1].trim();
        // 只要「版本号开头」的章节（2.5.31 …），其它章节（第 X 页 / 说明）忽略
        当前 = /^[0-9]+\.[0-9]+/.test(标) ? { 标题: 标, 正文: [] } : null;
        if (当前) 条.push(当前);
        continue;
      }
      if (当前) 当前.正文.push(L);
    }
    return 条.map((x) => ({
      标题: x.标题,
      版本: (x.标题.match(/^[0-9]+(?:\.[0-9]+)*/) || [""])[0],
      正文: (Array.isArray(x.正文) ? x.正文.join("\n") : String(x.正文 || "")).replace(/\n{3,}/g, "\n\n").replace(/<!--PAGE-->/g, "").trim()
    }));
  } catch (e) { return 条; }
}


// 2.9.11：把合并后的公告切成页 —— 每页最多 10 条；正文累计超 900 字提前结页。
//   2.9.11 收尾：单条正文本身超 900 字时，按段落/行边界拆成多段（每段 ≤ 公告拆段字数），
//   每段连续独占一页展示（条目序号不变，页数会大于条目数），不再「独占一页全文保留」。
export function 公告拆段(正文, 上限) {
  const 段组 = [];
  let cur = "";
  const 收 = (s) => { if (s) 段组.push(s); };
  for (const L of String(正文).split("\n")) {
    // 极端兜底：单行超上限（当前文档最长行 510 字，正常走不到）—— 按上限硬切，内容不丢
    if (L.length > 上限) {
      收(cur); cur = "";
      for (let j = 0; j < L.length; j += 上限) 收(L.slice(j, j + 上限));
      continue;
    }
    if (cur && cur.length + 1 + L.length > 上限) { 收(cur); cur = L; }
    else cur = cur ? cur + "\n" + L : L;
  }
  收(cur);
  return 段组;
}


