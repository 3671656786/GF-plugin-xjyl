// 2.5.55（需求 B）：**控制台重启 = 自动出招停止**（不再自动续跑）
//   原因：重启是运维动作，不该让玩家在不知情时继续消耗自动卡。
//   做法：启动时把所有「上次没结束」的自动出招标记为「控制台重启已中断」并移出活跃索引。
//   · 已经出掉的招 / 已扣的卡**不返还**（卡是按招扣的，没出的招本来就没扣）
//   · 战斗本身不丢：战斗记录仍在，玩家可以继续 `星甲普攻` 或重新 `星甲一键出招`
export function 清理重启的自动出招(ctx) {
  const list = 自动索引(ctx);
  if (!list.length) return 0;
  let n = 0;
  for (const uid0 of list) {
    const st = 读自动(ctx, uid0);
    if (!st) continue;
    if (st.开 && !st.结束) {
      st.开 = false;
      st.结束 = "控制台重启已中断（不返还已出的招）";
      st.停时 = Date.now();
      写自动(ctx, uid0, st);
      n += 1;
    }
  }
  try { dset(ctx, P.自动战斗索引, "列表", []); } catch (e) { /* ignore */ }
  if (n && ctx && ctx.logger && ctx.logger.info) ctx.logger.info("[xjyl] 控制台重启：已中断 " + n + " 个进行中的自动出招");
  return n;
}
