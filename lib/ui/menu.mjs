/* ---------- 2.3.0 使用指南（独立 md 文档，分页发送，每页 ≤1000 字） ---------- */
export const 指南每页字数 = 1000;


export function 读指南(ctx) {
  try {
    const p = 解析插件相对路径(ctx, "使用指南.md");
    if (!p || !fs.existsSync(p)) return [];
    const 文 = fs.readFileSync(p, "utf8");
    return 文.split(/<!--PAGE-->/).map((x) => x.trim()).filter(Boolean);
  } catch (e) { return []; }
}


