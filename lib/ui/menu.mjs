// 统一的分组菜单渲染（完整指令菜单 / 完整菜单 共用）
export async function 分组菜单(ctx, t, ev, 组表, 标题前缀, 标题图标, 每页组, 指令名, 页) {
  const 主 = (() => { try { return ev ? isOwner(ctx, ev) : false; } catch (e) { return false; } })();
  const 组列表 = 组表.filter((g) => !g.主人 || 主);
  const 总页 = Math.max(1, Math.ceil(组列表.length / 每页组));
  const 页码 = Math.max(1, Math.min(Math.floor(Number(页) || 1), 总页));
  const 组 = 组列表.slice((页码 - 1) * 每页组, 页码 * 每页组);
  const 行 = ["共 " + 总页 + " 页" + (总页 > 1 ? "　翻页：`星甲" + 指令名 + "#页码`" : ""), ""];
  for (const g of 组) {
    行.push("**" + g.组 + "**");
    // 2.9.4（需求 3）：正文改蓝色（沿用插件的 <qqbot-cmd-input> 蓝色指令标记，点一下还能填指令）
    for (const c of g.条) 行.push("- " + 蓝字原文(c[0], c[0] + "　" + c[1]));
    行.push("");
  }
  行.push("💡 所有指令都以「星甲」开头；带 # 的是参数。" + (页码 < 总页 ? "发 `星甲" + 指令名 + "#" + (页码 + 1) + "` 看下一页。" : ""));
  // 一行最多 5 个按钮：上一页 + 页码 + 下一页，页码最多显示 3 个（以当前页为中心），
  //   页码多的时候才不会挤爆键盘 —— 想直接跳页还是发 `星甲<指令名>#页码`。
  const 翻页组 = [];
  if (页码 > 1) 翻页组.push(btn("fm_p", "⬅上一页", 指令名 + "#" + (页码 - 1)));
  const 起 = Math.max(1, Math.min(页码 - 1, Math.max(1, 总页 - 2)));
  for (let i = 起; i < 起 + 3 && i <= 总页; i++) 翻页组.push(btn("fm" + i, i === 页码 ? "[" + i + "]" : String(i), 指令名 + "#" + i));
  if (页码 < 总页) 翻页组.push(btn("fm_n", "下一页➡", 指令名 + "#" + (页码 + 1)));
  const 底组 = [btn("fn_a", "另个菜单", 指令名 === "完整菜单" ? "完整指令菜单" : "完整菜单")];
  await reply(ctx, t, 行.join("\n"), {
    标题: 标题图标 + " " + 标题前缀 + " " + 页码 + "/" + 总页,
    行组: [row.apply(null, 翻页组), row.apply(null, 底组.concat([btn("fm_m", "星甲菜单", "星甲菜单"), btn("fm_g", "使用指南", "指南"), btn("fm_i", "属性", "属性")]))]
  });
}


