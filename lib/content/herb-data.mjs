export const 开垦灵石基数 = 300;
export function 开垦费(第几块) {
  const n = Math.max(2, Math.min(田上限, Math.floor(Number(第几块) || 2)));
  const 灵石 = 开垦灵石基数 * n * n;
  return { 田: n, 灵石: 灵石, 星羽: 灵石折星羽(灵石) };
}

/* ---------- 2.5 田块升级费（三货币，累计 500 万星羽 + 250 万金币 + 100 万花） ----------
 * 需求：每块灵田 Lv1 → Lv10 的**累计**成本 = 星羽 5,000,000 + 金币 2,500,000 + 花 1,000,000。
 * 推导（9 次升级，权重按目标等级 2..10 即 1..9，Σ = 45）：
 *   星羽：5,000,000 ÷ 45 = 111,111.11 → 每级 **111,111 × L**，累计 111,111×45 = 4,999,995（误差 5，0.0001%）
 *   金币：2,500,000 ÷ 45 =  55,555.56 → 每级 ** 55,555 × L**，累计  55,555×45 = 2,499,975（误差 25，0.001%）
 *   花　：1,000,000 ÷ 45 =  22,222.22 → 每级 ** 22,222 × L**，累计  22,222×45 =   999,990（误差 10，0.001%）
 * 逐级示例：Lv1→2 星羽 111,111 + 金币 55,555 + 花 22,222；Lv9→10 星羽 999,999 + 金币 499,995 + 花 199,998。
 * 全部三档误差 < 0.01%，满足「累计正好 500 万 / 250 万 / 100 万」的口径。
 */
export const 田升级权重和 = 45;                 // 1+2+…+9
export const 田升级星羽总 = 5000000;
export const 田升级金币总 = 2500000;
export const 田升级花总 = 1000000;
export const 田升级星羽基数 = Math.floor(田升级星羽总 / 田升级权重和);   // 111,111
export const 田升级金币基数 = Math.floor(田升级金币总 / 田升级权重和);   //  55,555
export const 田升级花基数 = Math.floor(田升级花总 / 田升级权重和);       //  22,222

// 升到第 L 级（L = 2..10）的费用：三种货币同时扣（花走背包道具）
export function 田升级费(下一级) {
  const L = Math.max(2, Math.min(田等级上限, Math.floor(Number(下一级) || 2)));
  const 权 = L - 1;                              // 权重 1..9
  return { 星羽: 田升级星羽基数 * 权, 金币: 田升级金币基数 * 权, 花: 田升级花基数 * 权 };
}

// 单块田 Lv1 → Lv10 的累计成本（面板/帮助/测试用）
export function 田升满总费() {
  let 星羽 = 0, 金币 = 0, 花 = 0;
  for (let L = 2; L <= 田等级上限; L++) {
    const 费 = 田升级费(L);
    星羽 += 费.星羽; 金币 += 费.金币; 花 += 费.花;
  }
  return { 星羽: 星羽, 金币: 金币, 花: 花 };
}

