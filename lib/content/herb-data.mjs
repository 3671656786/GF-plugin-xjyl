/* ============================================================
 * 数值口径（本文件的注释、lib/game/herb.mjs 的注释、.workbuddy/test/dbg-herb.mjs 的断言必须一致）
 * ------------------------------------------------------------
 * 1) 汇率：灵石兑星羽 = 2 —— 1 灵石 = 2 星羽（本作没有独立「灵石」货币，灵种按灵石标价，
 *    买种时按这个汇率折成星羽扣款；玩家面板同时显示「灵石价 = 星羽价」两种口径）。
 * 2) 药材单价（星羽/份）= 灵种价(灵石) × 2 ÷ 该灵种的基础产量（田块 Lv.1 产量）。
 *    → Lv.1 田刚好「买种钱 = 全收药材价值」（不赚不赔）；赚钱靠田块等级
 *      （每升 1 级产量翻一倍，Lv.1 ×1 → Lv.10 ×10，单田产量封顶 20 份）。
 * 3) 成药成本（星羽/份）= 该药方材料成本总价 ÷ 基准份数（炼药 Lv.1 每轮产出 = 基准份数）。
 * 4) 商店同效果折算价 = 效果 × 商店单位效果价：
 *    · 回血：商店最高档【太虚还魂汤 4000 星羽 / 5000 血 = 0.8 星羽/血】
 *    · 回蓝：商店最高档【幽泉灵乳 500 星羽 / 200 蓝 = 2.5 星羽/蓝】
 *    （成药效果全部高于商店最高档 —— 回血最高 23000、回蓝最高 900，
 *      玩家真实的「同效果替代成本」就是买 N 份商店最高档，所以拿最高档的单价折算）
 *    · 商店参考数据来源：lib/game/rebirth.mjs 的 药品集 / 药品回血 / 药品回蓝 + 商店价
 *      （赤霄血露 30 回 60、碧髓回春液 120 回 200、玄元凝血膏 380 回 600、
 *        九幽血髓酿 1200 回 2000、太虚还魂汤 4000 回 5000；青霜灵液 150 回 50 蓝、幽泉灵乳 500 回 200 蓝）
 * 5) 目标：成药成本 ≈ 商店同效果价的 **70%**（测试容差 ±5%，即 66.5% ~ 73.5%）。
 *    6 个药方的效果**全部高于商店最高档**（回血 > 5000、回蓝 > 200），按同比例折算后实测：
 *    · 凝露散    回血  5200：星纹叶×4(1000) + 露华藤×12(6000) + 赤心草×10(10000) + 碧髓花×6(12000) = 29000
 *                          ÷ 基准 10 份 = 2900/份 ；商店等价 5200×0.8=4160  → 2900/4160   = 69.71%
 *    · 赤心丹    回血  8700：露华藤×8(4000) + 赤心草×8(8000) + 碧髓花×6(12000) + 玄霜根×3(12000) + 幽泉苔×1(8000) = 44000
 *                          ÷ 9 份 = 4888.9/份；商店等价 8700×0.8=6960  → 4889/6960   = 70.24%
 *    · 玄霜玉液  回血 14700：赤心草×6(6000) + 碧髓花×6(12000) + 玄霜根×4(16000) + 幽泉苔×2(16000) + 紫宸果×1(16000) = 66000
 *                          ÷ 8 份 = 8250/份 ；商店等价 14700×0.8=11760 → 8250/11760  = 70.15%
 *    · 太虚还春丹 回血 24500：碧髓花×4(8000) + 玄霜根×4(16000) + 幽泉苔×3(24000) + 紫宸果×1(16000) + 太虚芝×1(32000) = 96000
 *                          ÷ 7 份 = 13714.3/份；商店等价 24500×0.8=19600 → 13714/19600 = 69.97%
 *    · 霜华露    回蓝   300：星纹叶×5(1250) + 露华藤×4(2000) + 赤心草×2(2000) = 5250
 *                          ÷ 10 份 = 525/份 ；商店等价 300×2.5=750   → 525/750    = 70.00%
 *    · 泉心玉髓  回蓝  1000：露华藤×4(2000) + 赤心草×4(4000) + 碧髓花×2(4000) + 玄霜根×1(4000) = 14000
 *                          ÷ 8 份 = 1750/份 ；商店等价 1000×2.5=2500  → 1750/2500  = 70.00%
 *    说明：档位越高 → 药材**种类越多**（4→5→5→5 种）、单价越高（稀有药材）；低档用便宜药材所以单方份数更多。
 * ============================================================ */

