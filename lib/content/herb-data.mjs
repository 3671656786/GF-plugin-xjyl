/* ---------- 五、成本换算 ---------- */
export function 药方材料成本(药方) {
  const r = typeof 药方 === "string" ? 药方找(药方) : 药方;
  if (!r) return 0;
  let 共 = 0;
  for (const [名, 数] of r.需) 共 += 药材单价(名) * (Number(数) || 0);
  return 共;
}

// 成药成本（星羽/份）= 材料总价 ÷ 基准份数（炼药 Lv.1 口径）
export function 成药成本(名) {
  const it = 成药找(名);
  if (!it) return 0;
  return 药方材料成本(it.药方) / Math.max(1, it.基准);
}

// 商店同效果折算价（星羽/份）
export function 成药商店等价(名) {
  const it = 成药找(名);
  if (!it) return 0;
  return it.类型 === "蓝" ? it.蓝 * 商店回蓝单价 : it.血 * 商店回血单价;
}

export function 成本占比(名) {
  const 等价 = 成药商店等价(名);
  return 等价 > 0 ? 成药成本(名) / 等价 : 0;
}

