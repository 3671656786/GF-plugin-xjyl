// 有食物加成后的实际干活间隔（秒）：基础 × (1 − 加成)，仍夹在 60~180
export function 加成后间隔(基础秒, 加成) {
  const 基 = Math.max(干活间隔下限, Math.min(干活间隔上限, Math.round(Number(基础秒) || 干活间隔上限)));
  const b = Math.max(0, Math.min(0.5, Number(加成) || 0));
  return Math.max(干活间隔下限, Math.min(干活间隔上限, Math.round(基 * (1 - b))));
}


/* ---------- 自检：数据表内部一致性（测试与管理员排障共用） ---------- */
export function 宠物自检() {
  const 问题 = [];
  if (宠物表.length < 6) 问题.push("宠物少于 6 只（" + 宠物表.length + "）");
  const 名集 = new Set(), 号集 = new Set(), 名重 = [], 号重 = [];
  for (const x of 宠物表) {
    if (名集.has(x.名)) 名重.push(x.名);
    名集.add(x.名);
    if (号集.has(x.编号)) 号重.push(x.编号);
    号集.add(x.编号);
  }
  if (名重.length) 问题.push("宠物重名：" + 名重.join("/"));
  if (号重.length) 问题.push("编号重复：" + 号重.join("/"));
  for (const x of 宠物表) {
    if (稀有度表.indexOf(x.稀有度) < 0) 问题.push(x.名 + " 稀有度非法：" + x.稀有度);
    const 价 = 领养价(x);
    for (const k of 领养货币) {
      if (!(价[k] > 0)) 问题.push(x.名 + " 领养价." + k + " 必须 > 0（本轮改成四货币）");
    }
    if (!(x.效率 >= 1 && x.效率 <= 3)) 问题.push(x.名 + " 效率应在 1~3");
    if (!(x.单轮块 >= 1 && x.单轮块 <= 2)) 问题.push(x.名 + " 单轮块应在 1~2");
    if (!(x.消耗 >= 1 && x.消耗 <= 20)) 问题.push(x.名 + " 每轮消耗应在 1~20");
    if (!x.技能) 问题.push(x.名 + " 缺技能描述");
    for (let L = 1; L <= 等级上限; L++) {
      const 秒 = 干活间隔秒(x, L);
      if (秒 < 干活间隔下限 || 秒 > 干活间隔上限) 问题.push(x.名 + " Lv" + L + " 间隔越界：" + 秒);
      const p = 摸鱼概率(x, L);
      if (!(p >= 摸鱼概率下限 && p <= 摸鱼概率上限)) 问题.push(x.名 + " Lv" + L + " 摸鱼概率越界：" + p);
    }
  }
  // 稀有度越高越贵、越快（同稀有度内按编号递增）；四种货币必须**全部**递增
  const 序 = 宠物表.map((x) => [稀有度序(x.稀有度), 领养价(x), x.效率, x.名]);
  for (let i = 1; i < 序.length; i++) {
    if (序[i][0] < 序[i - 1][0]) 问题.push("稀有度顺序倒退：" + 序[i - 1][3] + " → " + 序[i][3]);
    for (const k of 领养货币) {
      if (序[i][1][k] <= 序[i - 1][1][k]) 问题.push("领养价." + k + " 未递增：" + 序[i - 1][3] + " → " + 序[i][3]);
    }
    if (序[i][2] < 序[i - 1][2]) 问题.push("效率倒退：" + 序[i - 1][3] + " → " + 序[i][3]);
    // 价格上调后必须仍然「贵得有意义」：星羽逐档至少 +30%
    if (序[i][1].星羽 < 序[i - 1][1].星羽 * 1.3) 问题.push("领养星羽涨幅过低：" + 序[i - 1][3] + " → " + 序[i][3]);
  }
  // 摸鱼：低效宠物更容易摸鱼、等级越高越专注（逐点递减）
  for (const x of 宠物表) {
    for (let L = 2; L <= 等级上限; L++) {
      if (摸鱼概率(x, L) > 摸鱼概率(x, L - 1)) 问题.push(x.名 + " Lv" + L + " 摸鱼概率未随等级下降");
    }
  }
  for (let i = 1; i < 宠物表.length; i++) {
    if (摸鱼概率(宠物表[i], 1) > 摸鱼概率(宠物表[i - 1], 1)) 问题.push("摸鱼概率未随效率下降：" + 宠物表[i - 1].名 + " → " + 宠物表[i].名);
  }
  if (摸鱼概率(宠物表[0], 1) <= 摸鱼概率(宠物表[宠物表.length - 1], 1)) 问题.push("低效宠物挤不出更高摸鱼概率（公式写反了？）");
  if (!(喂食星羽价(宠物表[0]) >= 800)) 问题.push("喂食星羽价没跟着上调（应 ≥ 800）");
  for (let i = 1; i < 宠物表.length; i++) {
    const 上 = 喂食星羽价(宠物表[i - 1]);
    const 今 = 喂食星羽价(宠物表[i]);
    if (今 < 上) 问题.push("喂食星羽价倒退：" + 宠物表[i - 1].名 + " → " + 宠物表[i].名);
    // 稀有度往上走一档时必须更贵（同稀有度内价格相同是允许的）
    if (稀有度序(宠物表[i].稀有度) > 稀有度序(宠物表[i - 1].稀有度) && 今 <= 上) {
      问题.push("喂食星羽价未随稀有度递增：" + 宠物表[i - 1].名 + " → " + 宠物表[i].名);
    }
  }
  // 后台时钟参数
  if (!(后台滴答毫秒 >= 100 && 后台滴答毫秒 <= 2000)) 问题.push("后台滴答毫秒 应在 100~2000");
  if (!(后台刷新毫秒 >= 后台滴答毫秒)) 问题.push("后台刷新毫秒 不能小于滴答");
  if (!(每拍最多玩家 >= 1 && 每拍最多玩家 <= 5)) 问题.push("每拍最多玩家 应在 1~5");
  if (!(后台日志上限 >= 3 && 后台日志上限 <= 30)) 问题.push("后台日志上限 应在 3~30");
  // 食物表（小屋）：至少 2 种、名字唯一、加成分三档、价格递增
  if (食物表.length < 2) 问题.push("食物少于 2 种（" + 食物表.length + "）");
  const 食名 = new Set();
  for (const f of 食物表) {
    if (食名.has(f.名)) 问题.push("食物重名：" + f.名);
    食名.add(f.名);
    if (!(f.回体 > 0)) 问题.push(f.名 + " 回体应 > 0");
    if (!(f.星羽 > 0)) 问题.push(f.名 + " 星羽价应 > 0");
    if (f.效率 > 0 && !(f.效率秒 >= 60)) 问题.push(f.名 + " 效率加成需要持续秒数");
    if (!f.说明) 问题.push(f.名 + " 缺说明");
  }
  for (let i = 1; i < 食物表.length; i++) {
    if (食物表[i].星羽 <= 食物表[i - 1].星羽) 问题.push("食物价格未递增：" + 食物表[i - 1].名 + " → " + 食物表[i].名);
  }
  if (加成后间隔(180, 0) !== 180 || 加成后间隔(180, 0.2) !== 144) 问题.push("加成后间隔公式不对");
  return { ok: 问题.length === 0, 问题: 问题 };
}
