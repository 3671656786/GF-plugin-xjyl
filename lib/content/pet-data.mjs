// 参数既可以是宠物对象，也可以是名字 / 编号（面板与指令都直接传玩家输入）
function 取宠(宠) {
  if (宠 && typeof 宠 === "object") return 宠;
  return 宠物找(宠) || 宠物表[0];
}


// 体力上限：Lv1 = 100，每级 +5（Lv10 = 145）
export function 体力上限算(等级) {
  const L = Math.max(1, Math.min(等级上限, Math.floor(Number(等级) || 1)));
  return 体力上限 + (L - 1) * 体力上限每级;
}


// 干活间隔（秒）：效率越高越快，等级每级 -4 秒，夹在 60~180
export function 干活间隔秒(宠, 等级) {
  const o = 取宠(宠);
  const 率 = Math.max(0.5, Number(o.效率) || 1);
  const L = Math.max(1, Math.min(等级上限, Math.floor(Number(等级) || 1)));
  const 基 = Math.round(干活间隔上限 / 率);
  return Math.max(干活间隔下限, Math.min(干活间隔上限, 基 - (L - 1) * 等级提速每级));
}


// 每轮体力消耗（按宠物表写死的值，等级不减免 —— 省钱靠喂食，不靠升级）
