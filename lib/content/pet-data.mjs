/* ---------- 查找（名字 / 编号都认） ---------- */
export function 宠物找(键) {
  const k = String(键 === undefined || 键 === null ? "" : 键).trim();
  if (!k) return null;
  return 宠物表.filter((x) => x.名 === k || String(x.编号) === k)[0] || null;
}

export function 宠物找号(编号) {
  const i = Math.floor(Number(编号) || 0);
  return 宠物表.filter((x) => x.编号 === i)[0] || null;
}

export function 宠物名表() { return 宠物表.map((x) => x.名); }


