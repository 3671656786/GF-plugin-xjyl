/* ---------- 喂食价格（本轮改造：跟着领养价一起上调） ----------
 * 两条喂食途径：
 *   ① 背包作物：**免费**（消耗 1 个作物，体力 +喂食作物恢复 30）—— 仍然是最划算的方式；
 *   ② 花星羽买现成的：喂食星羽价 = 800 + 稀有度序 × 700，传说再 +1200 → 800 / 1500 / 2200 / 4100 星羽。
 *      旧价（200 / 450 / 700 / 1050）在四货币领养价面前太便宜，等于「养不起就花小钱无限续」，
 *      所以同步上调约 4 倍；相对地，作物喂食（+30）比星羽喂食（+15）更划算，引导玩家去种田。
 */
export const 喂食价基数 = 800;
export const 喂食价每档 = 700;
export const 喂食价传说附加 = 1200;

export function 喂食星羽价(宠) {
  const o = 取宠(宠);
  const 序 = 稀有度序(o.稀有度);
  return 喂食价基数 + 序 * 喂食价每档 + (序 === 3 ? 喂食价传说附加 : 0);
}


/* ---------- 领养价（四货币） ---------- */
// 统一成 { 星羽, 金币, 花, 星石 } 四个正整数（老表只写 1 个数字时也兼容 → 全算星羽）
export function 领养价(宠) {
  const o = 取宠(宠);
  const 源 = o && o.价 && typeof o.价 === "object" ? o.价 : { 星羽: Number(o && o.价) || 0 };
  const out = {};
  for (const k of 领养货币) out[k] = Math.max(0, Math.floor(Number(源[k]) || 0));
  return out;
}


// 只关心星羽那一项时用（面板/提示里算「星羽差多少」）
export function 领养价星羽(宠) { return 领养价(宠).星羽; }


// 「5,000 星羽 + 300 金币 + 20 朵花 + 1 颗星石」—— 每项都带单位（面板/回复共用）
export function 领养价文案(宠) {
  const 价 = 领养价(宠);
  return 领养货币
    .filter((k) => 价[k] > 0)
    .map((k) => String(价[k]).replace(/\B(?=(\d{3})+(?!\d))/g, ",") + " " + 领养货币单位[k])
    .join(" + ");
}


/* ---------- 摸鱼（本轮改造 ③） ----------
 * 干活时先掷一次骰子，命中就**摸鱼**：本次不干活、直接回去休息、回少量体力（8~15 点）。
 * 概率公式：摸鱼概率 = clamp( 摸鱼基础概率 × (摸鱼效率基准 ÷ 效率) − (等级−1) × 摸鱼每级减幅,
 *                              摸鱼概率下限, 摸鱼概率上限 )
 *   · 效率越低越容易摸鱼：效率 1.0 → 20%，效率 1.4 → 14.3%，效率 3.0 → 6.7%；
 *   · 等级越高越专注：每级 -1.2 个百分点（星尾狐 Lv10 = 9.2%，星穹龙 Lv10 触底 3%）；
 *   · 夹在 3%~25%，避免「刚领养就一直摸鱼」或「高稀有度永不摸鱼」两种极端。
 * 为什么要有：旧版宠物是纯「挂机产出」，没有任何性格；摸鱼让低稀有度宠物有短板、高稀有度有优势，
 *   同时给面板一个可读的「动态」（宠物摸鱼了 → 玩家的即时反馈）。
 */
export const 摸鱼基础概率 = 0.20;        // 效率 1.0、Lv1 时的触发概率
export const 摸鱼效率基准 = 1.0;          // 效率基准（÷ 实际效率）
export const 摸鱼每级减幅 = 0.012;        // 每升 1 级，概率 -1.2 个百分点
export const 摸鱼概率下限 = 0.03;         // 最低 3%（再勤快的宠物也可能偶尔摸鱼）
export const 摸鱼概率上限 = 0.25;         // 最高 25%（再懒也不会一直不干活）
export const 摸鱼回体最小 = 8;            // 摸鱼时回复的体力下限
export const 摸鱼回体最大 = 15;           // 摸鱼时回复的体力上限

export function 摸鱼概率(宠, 等级) {
  const o = 取宠(宠);
  const 率 = Math.max(0.1, Number(o.效率) || 1);
  const L = Math.max(1, Math.min(等级上限, Math.floor(Number(等级) || 1)));
  const 原 = 摸鱼基础概率 * (摸鱼效率基准 / 率) - (L - 1) * 摸鱼每级减幅;
  const 夹 = Math.max(摸鱼概率下限, Math.min(摸鱼概率上限, 原));
  return Math.round(夹 * 1000) / 1000;    // 保留 3 位小数，面板与测试都好读
}

export function 摸鱼文案概率(宠, 等级) {
  return Math.round(摸鱼概率(宠, 等级) * 100) + "%";
}


